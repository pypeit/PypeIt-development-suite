"""
Vet tests of the Keck/OSIRIS Kn3/0.035" narrowband reduction (milestone M5,
task 1): the nova V1405 Cas observed on 2024-08-13 (KOA), two 300-s
object/sky pairs, rectified with the Keck matrix of the 230701-250310
validity epoch.

They inspect the products of the dev-suite ``keck_osiris/Kn3_035`` reduce
test in ``REDUX_OUT``:

1. one spectrum per lenslet of the narrowband layout (51 lenslet columns),
   each with most of its spectral window usable, vacuum wavelengths
   inside the Kn3 band;
2. the nova is a point source inside the field, with Br gamma in emission.

Tests skip when the products are missing.

Generated by JXP and Claude.
"""
from pathlib import Path

import numpy as np
import pytest

from astropy.io import fits

from pypeit.specobjs import SpecObjs


SCI = 'spec1d_OS.20240813.*-v1405cas*.fits'
BAND = (21090., 22420.)          # Kn3 lenslet windows (Angstrom)
BRG = 21661.2                    # Br gamma, vacuum


@pytest.fixture
def spec1d_files(redux_out):
    """
    The Kn3_035 spec1d files of the nova (one per A-B pair).

    Generated by JXP and Claude.
    """
    rdx = Path(redux_out) / 'keck_osiris' / 'Kn3_035' / 'Science'
    files = [f for f in sorted(rdx.glob(SCI)) if '_ps' not in f.name]
    if len(files) == 0:
        pytest.skip(f'No {SCI} in {rdx}')
    return files


def test_kn3_lenslets(spec1d_files):
    """Narrowband layout: one usable spectrum per lenslet."""
    for f in spec1d_files:
        sobjs = SpecObjs.from_fitsfile(f, chk_version=False)
        hdr = fits.getheader(f)
        ids = np.asarray(sobjs.MASKDEF_ID)
        ngood = np.array([np.sum(s.BOX_MASK) for s in sobjs])
        print(f'{f.name}: {sobjs.nobj} lenslet spectra; good pixels per '
              f'lenslet median {np.median(ngood):.0f}, min {ngood.min()}')
        # 51 lenslet columns x 64 rows minus the unilluminated corners
        assert sobjs.nobj == 3040
        assert len(np.unique(ids)) == sobjs.nobj
        _, ccol = np.divmod(ids, 51)
        assert ccol.min() == 0 and ccol.max() == 50
        assert hdr['AIRORVAC'] == 'vac'
        # Every lenslet keeps most of its window (no lenslet lost at the
        # edges of the narrowband layout)
        assert ngood.min() > 300
        good = np.concatenate([s.BOX_WAVE[s.BOX_MASK] for s in sobjs])
        assert np.percentile(good, 1) > BAND[0] - 20.
        assert np.percentile(good, 99) < BAND[1] + 20.


def test_kn3_nova(spec1d_files):
    """The nova is inside the field and shows Br gamma in emission."""
    for f in spec1d_files:
        sobjs = SpecObjs.from_fitsfile(f, chk_version=False)
        ids = np.asarray(sobjs.MASKDEF_ID)
        cont = np.array([np.median(s.BOX_COUNTS[s.BOX_MASK])
                         if np.sum(s.BOX_MASK) > 50 else np.nan
                         for s in sobjs])
        crow, ccol = np.divmod(ids, 51)
        k0 = int(np.nanargmax(cont))
        # 3x3 lenslets around the continuum peak
        near = (np.abs(crow - crow[k0]) <= 1) & (np.abs(ccol - ccol[k0]) <= 1)
        grid = np.arange(21200., 22200., 2.)
        spec = np.zeros(grid.size)
        for k in np.where(near)[0]:
            s = sobjs[k]
            m = s.BOX_MASK
            spec += np.interp(grid, s.BOX_WAVE[m], s.BOX_COUNTS[m])
        on = np.abs(grid - BRG) < 40.
        side = (grid > 21250.) & (grid < 21450.)
        ew = np.sum(spec[on] / np.median(spec[side]) - 1.) * 2.
        print(f'{f.name}: continuum peak at lenslet row {crow[k0]}, col '
              f'{ccol[k0]} ({cont[k0]:.0f} counts/pixel vs median '
              f'{np.nanmedian(cont):.0f}); Br gamma EW {ew:.1f} A')
        # A point source well above the median lenslet, inside the field
        assert cont[k0] > 20. * np.nanmedian(np.abs(cont))
        assert 2 <= ccol[k0] <= 48 and 2 <= crow[k0] <= 63
        assert ew > 5.
