def test_spec1d_lenslets(spec1d):
    """One spectrum per lenslet, lenslet ids, vacuum wavelengths."""
    sobjs = SpecObjs.from_fitsfile(spec1d, chk_version=False)
    hdr = fits.getheader(spec1d)
    ids = np.asarray(sobjs.MASKDEF_ID)
    print(f'{sobjs.nobj} spectra; {len(np.unique(ids))} lenslet ids; '
          f'AIRORVAC = {hdr.get("AIRORVAC")}')
    # Hn3 is narrowband: 1024 slices of three (or four) lenslets
    assert 2900 < sobjs.nobj < 3300
    assert len(np.unique(ids)) == sobjs.nobj
    assert np.all((ids >= 0) & (ids < 66 * 51))
    assert hdr['AIRORVAC'] == 'vac'
    good = np.concatenate([s.BOX_WAVE[s.BOX_MASK] for s in sobjs])
    assert np.median(good) > BAND[0] and np.median(good) < BAND[1]


def test_quasar_position(spec1d):
    """The collapsed spec1d image of 3C 273 matches the DRP cube."""
    if not REF.is_file():
        pytest.skip(f'Missing {REF}')
    sobjs = SpecObjs.from_fitsfile(spec1d, chk_version=False)
    img = np.zeros((66, 51))
    for s in sobjs:
        crow, ccol = divmod(int(s.MASKDEF_ID), 51)
        g = s.BOX_MASK & (s.BOX_WAVE > BAND[0]) & (s.BOX_WAVE < BAND[1])
        img[crow, ccol] = np.sum(s.BOX_COUNTS[g])
    img = img[::-1]          # Keck I row flip of the DRP cube
    with fits.open(REF) as hdu:
        cube = hdu[0].data.astype(float)
        gpm = hdu[2].data == 9
        h = hdu[0].header
    wave = (h['CRVAL1'] + h['CDELT1'] * np.arange(cube.shape[2])) * 10.
    sel = (wave > BAND[0]) & (wave < BAND[1])
    dimg = np.where(gpm[..., sel], cube[..., sel], 0.).sum(axis=2).T

    def centroid(im):
        r0, c0 = np.unravel_index(np.argmax(im), im.shape)
        sub = im[r0 - 2:r0 + 3, c0 - 2:c0 + 3]
        rr, cc = np.mgrid[r0 - 2:r0 + 3, c0 - 2:c0 + 3]
        return (r0, c0), np.array([np.sum(sub * rr), np.sum(sub * cc)]) \
            / sub.sum()

    pk, cen = centroid(img)
    dpk, dcen = centroid(dimg)
    print(f'3C 273: PypeIt peak {pk} centroid {np.round(cen, 3)}; DRP peak '
          f'{dpk} centroid {np.round(dcen, 3)}')
    assert pk == QUASAR and dpk == QUASAR
    assert np.all(np.abs(cen - dcen) < 0.1)
