TILT_MAX = 0.05         # px over a block of 64 lenslets (design 8.3)
SCATTER_MAX = 0.1       # px, per-lenslet centroid scatter (design 8.3)
QUASAR = (30, 23)       # (row, col) of 3C 273 in the DRP cube (flipped)
BAND = (15960., 16740.)  # Angstrom, inside the Hn3 band


def lenslet_centroids(image, gpm, layout, sigdetect=10., fwhm=2.0):
    """
    OH-line centroids in every lenslet of the lenslet image.

    Generated by JXP and Claude.

    Args:
        image (`numpy.ndarray`_):
            Rectified lenslet image (nspec, nspat).
        gpm (`numpy.ndarray`_):
            Good-pixel mask.
        layout (`astropy.table.Table`_):
            Lenslet layout.
        sigdetect (:obj:`float`, optional):
            Detection threshold.
        fwhm (:obj:`float`, optional):
            Line FWHM in pixels.

    Returns:
        :obj:`list`: For each lenslet (layout row), the centroids and their
        significance from :func:`pypeit.core.arc.detect_lines`.
    """
    out = []
    for pos in layout['pos']:
        col = int(pos)
        spec = np.where(gpm[:, col], image[:, col], 0.)
        det = arc.detect_lines(spec, sigdetect=sigdetect, fwhm=fwhm,
                               fit_frac_fwhm=1.5, bpm=~gpm[:, col])
        out.append((det[2], det[7]))
    return out


def oh_line_tilts(image, gpm, layout, lam, nsig_ref=30., match=1.5,
                  nmin=40):
    """
    Residual tilts of the OH lines across each block.

    For every bright line of the reference lenslet of a block, the line is
    located in every lenslet of the block at the position predicted by its
    Keck solution; the residuals (measured - predicted) are fit with a line
    versus the lenslet row (4-sigma clipping).

    Generated by JXP and Claude.

    Args:
        image, gpm (`numpy.ndarray`_):
            Lenslet image and good-pixel mask.
        layout (`astropy.table.Table`_):
            Lenslet layout.
        lam (`numpy.ndarray`_):
            Keck wavelengths (nlenslet, nspec), in spectral-pixel order.
        nsig_ref (:obj:`float`, optional):
            Minimum significance of a line in the reference lenslet.
        match (:obj:`float`, optional):
            Maximum distance (px) between predicted and measured centroids.
        nmin (:obj:`int`, optional):
            Minimum number of lenslets with the line.

    Returns:
        :obj:`tuple`: Array (nline, 6) with block, wavelength, tilt over the
        block (slope x 63), intercept, robust scatter about the fit and the
        number of lenslets; and a list of (block, rows, residuals) for QA.
    """
    cents = lenslet_centroids(image, gpm, layout)
    ref = lr.block_reference(layout)
    pix = np.arange(image.shape[0], dtype=float)
    res, qa = [], []
    for b in range(layout.meta['nblock']):
        idx = np.where(layout['bidx'] == b)[0]
        tc, ns = cents[ref[b]]
        for t in tc[ns > nsig_ref]:
            wl = np.interp(t, pix, lam[ref[b]])
            rows, rr = [], []
            for i in idx:
                ti, ni = cents[i]
                if ti.size == 0:
                    continue
                p = np.interp(wl, lam[i], pix)
                k = np.argmin(np.abs(ti - p))
                if abs(ti[k] - p) > match or ni[k] < 10:
                    continue
                rows.append(int(layout['pos'][i]) % 64)
                rr.append(ti[k] - p)
            if len(rows) < nmin:
                continue
            rows, rr = np.array(rows), np.array(rr)
            keep = np.logical_not(sigma_clip(rr, sigma=4).mask)
            fit = np.polyfit(rows[keep], rr[keep], 1)
            resid = rr[keep] - np.polyval(fit, rows[keep])
            mad = 1.4826 * np.median(np.abs(resid - np.median(resid)))
            res.append((b, wl, fit[0] * 63, fit[1], mad, keep.sum()))
            qa.append((b, wl, rows, rr))
    return np.array(res), qa


def rectified_frame(setup, fname):
    """
    A raw OSIRIS frame processed into the rectified lenslet image.

    Generated by JXP and Claude.

    Args:
        setup (:obj:`str`):
            Dev-suite setup (``Hn3_100`` or ``Kbb_050``).
        fname (:obj:`str`):
            Raw file name.

    Returns:
        :obj:`dict`: ``image``, ``gpm``, ``layout``, ``lam`` (Keck
        wavelengths in Angstrom, spectral-pixel order) and ``hdr``.
    """
    raw = RAW_ROOT / setup
    path = raw / fname
    if not path.is_file():
        pytest.skip(f'Missing {path}')
    if not any((raw / 'calib').glob('*___infl_*')):
        pytest.skip(f'No rectification matrix in {raw / "calib"}')
    spec = load_spectrograph('keck_osiris')
    par = spec.default_pypeit_par()
    par['calibrations']['osiris_rectmat_dir'] = str(raw / 'calib')
    spec.set_runtime_par(par)
    img = rawimage.RawImage(str(path), spec, 1).process(
        par['scienceframe']['process'])
    hdr = fits.getheader(path)
    layout = spec.lenslet_layout()
    # nm -> Angstrom, spectral-pixel order
    lam = spec.lenslet_wavelengths(spec.frame_expansion(hdr))[:, ::-1] * 10.
    return dict(image=img.image, gpm=img.select_flag(invert=True),
                layout=layout, lam=lam, hdr=hdr)


def refinement_shifts(frame, lamps):
    """
    Per-lenslet OH shifts of a frame, as applied by the pipeline.

    Generated by JXP and Claude.

    Args:
        frame (:obj:`dict`):
            Output of :func:`rectified_frame`.
        lamps (:obj:`list`):
            Line lists.

    Returns:
        :obj:`tuple`: Shifts applied to every lenslet (pixels) and the
        per-lenslet measurements (NaN where not measured).
    """
    pos = np.asarray(frame['layout']['pos'])
    lines = waveio.load_line_lists(lamps)[1]
    applied, shift, _, _, _ = wvutils.fiber_sky_refinement(
        frame['image'][:, pos], frame['lam'].T, frame['gpm'][:, pos],
        lines, fwhm=2.0, mode='zeropoint')
    return applied, shift


def refined_wavelengths(lam, shifts):
    """
    Refined wavelengths ``lam(x - shift)`` of every lenslet.

    Generated by JXP and Claude.

    Args:
        lam (`numpy.ndarray`_):
            Wavelengths (nlenslet, nspec).
        shifts (`numpy.ndarray`_):
            Pixel shifts (nlenslet,).

    Returns:
        `numpy.ndarray`_: The refined wavelengths.
    """
    pix = np.arange(lam.shape[1], dtype=float)
    return np.array([np.interp(pix - s, pix, w) for w, s in zip(lam, shifts)])


def tilt_summary(res, label):
    """
    Print the tilt-test statistics.

    Generated by JXP and Claude.

    Args:
        res (`numpy.ndarray`_):
            Output of :func:`oh_line_tilts`.
        label (:obj:`str`):
            Label of the solution.
    """
    print(f'OH tilt test ({label}): {len(res)} (block, line) pairs in '
          f'{len(np.unique(res[:, 0]))} blocks; median |tilt| = '
          f'{np.median(np.abs(res[:, 2])):.3f} px, 90th pct = '
          f'{np.percentile(np.abs(res[:, 2]), 90):.3f} px; median scatter '
          f'= {np.median(res[:, 4]):.3f} px, 90th pct = '
          f'{np.percentile(res[:, 4], 90):.3f} px; median offset = '
          f'{np.median(res[:, 3]):.3f} px')


@pytest.fixture(scope='module', params=list(SETUPS.keys()))
def tilts(request):
    """
    OH-line tilt measurements on the sky frame of each setup, with the Keck
    solution and with the solution refined on the science frame.

    Generated by JXP and Claude.
    """
    setup = request.param
    cfg = SETUPS[setup]
    sky = rectified_frame(setup, cfg['sky'])
    sci = rectified_frame(setup, cfg['sci'])
    keck, _ = oh_line_tilts(sky['image'], sky['gpm'], sky['layout'],
                            sky['lam'])
    shifts, meas_sci = refinement_shifts(sci, cfg['lamps'])
    _, meas_sky = refinement_shifts(sky, cfg['lamps'])
    refined, _ = oh_line_tilts(sky['image'], sky['gpm'], sky['layout'],
                               refined_wavelengths(sky['lam'], shifts))
    tilt_summary(keck, f'{setup}, Keck coefficients')
    tilt_summary(refined, f'{setup}, refined on {cfg["sci"]}')
    ok = np.isfinite(meas_sci) & np.isfinite(meas_sky)
    print(f'{setup}: per-lenslet shifts science vs sky frame: correlation '
          f'{np.corrcoef(meas_sci[ok], meas_sky[ok])[0, 1]:.3f}, std of the '
          f'difference {np.std(meas_sci[ok] - meas_sky[ok]):.3f} px '
          f'({ok.sum()} lenslets)')
    return dict(setup=setup, keck=keck, refined=refined, meas_sci=meas_sci,
                meas_sky=meas_sky)


def test_oh_line_scatter(tilts):
    """Per-lenslet OH centroid scatter on the refined solution < 0.1 px."""
    assert len(tilts['refined']) > 150
    assert np.median(tilts['refined'][:, 4]) < SCATTER_MAX


def test_oh_line_tilt(tilts):
    """
    OH-line tilt over a block < 0.05 px on the refined solution (design
    8.3; closes the M3 criterion, M3 Q&A 1).
    """
    assert np.median(np.abs(tilts['refined'][:, 2])) < TILT_MAX


def test_oh_line_tilt_regression(tilts):
    """
    Guard against rectification failures (mis-mapped slices or a wrong
    ``hilo`` offset give pixel-size residuals): with the unrefined Keck
    solution, tilts well below a pixel; after the refinement, no offset
    between the lenslets and their solutions.
    """
    keck, refined = tilts['keck'], tilts['refined']
    assert np.median(np.abs(keck[:, 2])) < 0.2
    assert np.percentile(np.abs(keck[:, 2]), 90) < 0.5
    assert abs(np.median(refined[:, 3])) < 0.05


def test_refinement_repeatable(tilts):
    """
    The per-lenslet OH shifts measured on the science and on the sky frame
    agree (lenslet structure of the Keck coefficients, not noise).
    """
    a, b = tilts['meas_sci'], tilts['meas_sky']
    ok = np.isfinite(a) & np.isfinite(b)
    assert ok.sum() > 500
    assert np.std(a[ok] - b[ok]) < 0.04
    assert np.corrcoef(a[ok], b[ok])[0, 1] > 0.7


