"""
Vet tests of the Keck/OSIRIS reduction flow (milestones M3 and M4).

1. OH-line tilt test (design document, section 8, test 3), run on the
   sky frame of the Hn3/100 pair (``s160321_a002011``) and on an ``ISSKY=1``
   frame of the Kbb/050 NGC 3245 set (``OS.20240203.43383.79``).  The frame
   is processed by :class:`~pypeit.images.rawimage.RawImage` (rectification
   step included) into the lenslet image.  In every block (one Keck lenslet
   column of 64 lenslets) the centroids of the bright OH lines are measured
   in each lenslet with PypeIt's arc-line detection and compared with the
   positions predicted by the per-lenslet wavelength solution: the Keck
   coefficients *refined* on the OH lines of the paired science frame
   (``s160321_a002010`` / ``OS.20240203.42705.45``) with the same function
   as the pipeline (:func:`~pypeit.core.wavecal.wvutils.fiber_sky_refinement`,
   per-lenslet zero points; M4 task 4).  The refined solution must show no
   tilt across a block (fitted slope < 0.05 px over the 64 lenslets; this
   closes the M3 criterion) and a per-lenslet scatter < 0.1 px; a wrong
   slice/lenslet mapping or ``hilo`` offset would produce pixel-size
   offsets or a saw-tooth pattern (regression guard on the unrefined Keck
   solution).
2. The ``spec1d`` file written by ``run_pypeit`` on
   ``keck_osiris_hn3_100.pypeit`` (dev-suite ``REDUX_OUT``): one spectrum
   per lenslet, ``MASKDEF_ID`` = lenslet id, vacuum wavelengths, and the
   collapsed image of 3C 273 at the position of the DRP reference cube.

Only ``RAW_DATA/keck_osiris/{Hn3_100,Kbb_050}`` (and, for the spec1d tests,
the reduced data) are needed; tests skip otherwise.

Generated by JXP and Claude.
"""
