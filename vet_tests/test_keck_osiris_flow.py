def test_vacuum_wavelengths(sky_frame):
    """
    Lenslet wavelengths are vacuum: bright OH lines match the (vacuum)
    ``OH_NIRES`` list to well below the 4.4 A air-vacuum difference.
    """
    lines = waveio.load_line_lists(['OH_NIRES'])[0]
    lw = np.asarray(lines['wave'])
    lw = lw[(lw > BAND[0]) & (lw < BAND[1])]
    lay = sky_frame['layout']
    offs = []
    pix = np.arange(sky_frame['image'].shape[0], dtype=float)
    for i in lr.block_reference(lay):
        tc, ns = lenslet_centroids(sky_frame['image'], sky_frame['gpm'],
                                   lay[i:i + 1])[0]
        for w in np.interp(tc[ns > 30], pix, sky_frame['lam'][i]):
            d = lw - w
            k = np.argmin(np.abs(d))
            if abs(d[k]) < 2.0 and np.sum(np.abs(d) < 6.) == 1:
                offs.append(w - lw[k])
    offs = np.asarray(offs)
    print(f'OH lines: {offs.size} matches, median (data - list) = '
          f'{np.median(offs):.3f} A (DTMP7 = {sky_frame["hdr"].get("DTMP7")})')
    assert offs.size > 100
    assert abs(np.median(offs)) < 1.0


