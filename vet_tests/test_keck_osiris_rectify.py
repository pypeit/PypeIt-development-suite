"""
Vet test of the Keck/OSIRIS lenslet rectification (milestone M2).

The pair ``s160321_a002010 - s160321_a002011`` (Hn3, 0.100", 3C 273) is
rectified with ``s160318_c005___infl_Hn3_100.fits`` by both solvers of
:mod:`pypeit.core.lenslet_rectify`, resampled onto the DRP cube grid and
compared spaxel by spaxel with the DRP reference cube
``ref/s160321_a002010_Hn3_100_ref.fits``.

Two comparisons are made:

    - *DRP emulation*: the input is prepared exactly as the (September
      2016) DRP that produced the reference cube did it, including its
      cosmic-ray flagging (``cleancosmic_000.pro``, since disabled for
      H2RG data) and the row-indexing slip of the C quality mask.  This
      checks that the ``drp`` solver is a faithful port.
    - *PypeIt*: the input is prepared by ``pypeit_osiris_rectify`` (Keck
      static masks, PypeIt noise model, no cosmic-ray flagging; ``lstsq``
      weighted by the flux-independent read-noise + background variance
      since M3).  This is the M2 acceptance test.

Only the raw data in ``RAW_DATA/keck_osiris/Hn3_100`` are needed.

Generated by JXP and Claude.
"""
import os
from pathlib import Path

import numpy as np
import pytest

from astropy.io import fits

from pypeit.core import lenslet_rectify as lr
from pypeit.scripts.osiris_rectify import OsirisRectify
from pypeit.spectrographs.util import load_spectrograph


RAW = Path(os.getenv('PYPEIT_DEV', '.')) / 'RAW_DATA' / 'keck_osiris' \
    / 'Hn3_100'
FRAME_A = RAW / 's160321_a002010.fits'
FRAME_B = RAW / 's160321_a002011.fits'
MATRIX = RAW / 'calib' / 's160318_c005___infl_Hn3_100.fits'
REF = RAW / 'ref' / 's160321_a002010_Hn3_100_ref.fits'
QUASAR = (23, 30)       # (col, row) of the quasar in the DRP cube
SNR_MIN = 10.           # spaxels used for the statistics


def drp_cosmic_mask_2016(frame):
    """
    Emulate the cosmic-ray flagging of the September 2016 OSIRIS DRP.

    Thin wrapper of
    :func:`pypeit.core.lenslet_rectify.cosmic_mask_drp2016` (the port of
    ``cleancosmic_000.pro`` at OsirisDRP commit 9f11afd, moved to PypeIt in
    M3 as the fallback raw-frame cosmic-ray rule).

    Generated by JXP and Claude.

    Args:
        frame (`numpy.ndarray`_):
            Raw-orientation image (2048 x 2048).

    Returns:
        :obj:`tuple`: The image with flagged pixels set to 0 and the
        boolean mask of flagged pixels.
    """
    return lr.cosmic_mask_drp2016(frame)


def drp_c_quality_bpm(matrix, bpm):
    """
    Output mask of ``spatrectif_000.c`` including its row-indexing slip.

    The C code weighs the quality of detector rows 0-15 (instead of the
    rows of each slice) with the slice kernel.

    Generated by JXP and Claude.

    Args:
        matrix (:class:`~pypeit.core.lenslet_rectify.RectMatrix`):
            Rectification matrix.
        bpm (`numpy.ndarray`_):
            Raw bad-pixel mask (True = bad).

    Returns:
        `numpy.ndarray`_: Mask (ncol, nslice), True = bad.
    """
    _, fblame, _, fwpos = lr.blame_kernels(matrix)
    good = np.sum(fblame * np.logical_not(bpm[:matrix.nwin])[None], axis=1)
    return np.logical_not((good > 0.5) & fwpos).T


def to_cube(rect, rbpm, matrix, hdr, coeffs):
    """
    Resample a rectified frame to the DRP cube as the DRP does.

    Generated by JXP and Claude.

    Args:
        rect (`numpy.ndarray`_):
            Rectified image (ncol, nslice), ADU/s.
        rbpm (`numpy.ndarray`_):
            Its mask (True = bad).
        matrix (:class:`~pypeit.core.lenslet_rectify.RectMatrix`):
            Rectification matrix.
        hdr (`astropy.io.fits.Header`_):
            Raw header of frame A.
        coeffs (`numpy.ndarray`_):
            Keck wavelength coefficients.

    Returns:
        :obj:`tuple`: The cube and its good-voxel mask.
    """
    cube, gpm, _, wave = lr.resample_to_drp_grid(
        rect, matrix, hdr['SFILTER'], coeffs, hdr.get('DTMP7'),
        rect_bpm=rbpm)
    # PA_SPEC is missing: the DRP uses ROTPOSN - INSTANGL
    pa = hdr.get('PA_SPEC', hdr['ROTPOSN'] - hdr['INSTANGL'])
    cube = lr.drp_correct_dispersion(cube, wave, hdr['EL'], hdr['PARANG'],
                                     pa, float(hdr['SSCALE']))
    return cube, gpm


def spaxel_fluxes(cube, gpm, ref, refgpm):
    """
    Collapsed spaxel fluxes over the voxels good in both cubes.

    Generated by JXP and Claude.

    Args:
        cube, ref (`numpy.ndarray`_):
            Cubes (ncol, nrow, nwave) to compare.
        gpm, refgpm (`numpy.ndarray`_):
            Their good-voxel masks.

    Returns:
        :obj:`tuple`: Collapsed fluxes of ``cube`` and ``ref`` (ncol,
        nrow).
    """
    g = gpm & refgpm
    return np.where(g, cube, 0.).sum(axis=2), np.where(g, ref, 0.).sum(axis=2)


@pytest.fixture(scope='module')
def hn3(tmp_path_factory):
    """
    Inputs, script outputs and reference cube for the Hn3 pair.

    Generated by JXP and Claude.
    """
    for f in [FRAME_A, FRAME_B, MATRIX, REF]:
        if not f.is_file():
            pytest.skip(f'Missing {f}')
    spec = load_spectrograph('keck_osiris')
    hdr = fits.getheader(FRAME_A)
    out = dict(hdr=hdr, coeffs=spec.load_wave_coeffs(hdr['MJD-OBS']),
               matrix=lr.RectMatrix.from_file(MATRIX),
               exptime=spec.exptime_from_header(hdr))
    with fits.open(REF) as hdu:
        out['ref'] = hdu[0].data.astype(float)
        out['refgpm'] = hdu[2].data == 9
    # PypeIt-style rectification through the script (both solvers)
    odir = tmp_path_factory.mktemp('osiris_rect')
    for method in ['drp', 'lstsq']:
        ofile = odir / f'hn3_{method}.fits'
        OsirisRectify.main(OsirisRectify.parse_args(
            [str(FRAME_A), '--bkg', str(FRAME_B), '-m', str(MATRIX.parent),
             '--method', method, '-o', str(ofile)]))
        with fits.open(ofile) as hdu:
            t = out['exptime']
            rect = hdu['RECT'].data / t     # ADU -> ADU/s (DRP units)
            ivar = hdu['IVAR'].data * t**2
            rbpm = hdu['MASK'].data.astype(bool)
            out[f'time_{method}'] = hdu[0].header['RECTTIME']
        out[method] = to_cube(rect, rbpm, out['matrix'], hdr, out['coeffs'])
        if method == 'lstsq':
            # Spaxel S/N from the PypeIt noise model (lstsq variance)
            var = np.where(ivar > 0, 1. / np.where(ivar > 0, ivar, 1.), 0.)
            vcube, _ = to_cube(var, rbpm, out['matrix'], hdr, out['coeffs'])
            g = out['lstsq'][1] & out['refgpm']
            out['snr'] = np.where(g, out['ref'], 0.).sum(axis=2) \
                / np.sqrt(np.where(g, vcube, 0.).sum(axis=2) + 1e-30)
    return out


def test_drp_emulation(hn3):
    """The drp solver reproduces the DRP cube when fed the DRP input."""
    a = fits.getdata(FRAME_A, 0).astype(np.float32)
    b = fits.getdata(FRAME_B, 0).astype(np.float32)
    diff = lr.subtract_reference_rows(a - b)
    img, crmask = drp_cosmic_mask_2016(diff)
    matrix = hn3['matrix']
    rect, _, _ = lr.rectify_drp(img, crmask, matrix)
    cube, gpm = to_cube(rect, drp_c_quality_bpm(matrix, crmask), matrix,
                        hn3['hdr'], hn3['coeffs'])
    ref = hn3['ref']
    dmax = np.max(np.abs(cube - ref))
    f1, f0 = spaxel_fluxes(cube, gpm, ref, hn3['refgpm'])
    sel = hn3['snr'] > SNR_MIN
    med = np.median(np.abs(f1[sel] / f0[sel] - 1))
    print(f'DRP emulation: max |dv| = {dmax:.2e} ADU/s (ref peak '
          f'{ref.max():.1f}); median |frac| = {med:.2e}; quasar ratio = '
          f'{f1[QUASAR] / f0[QUASAR]:.6f}')
    assert dmax < 0.05
    assert med < 1e-3
    assert abs(f1[QUASAR] / f0[QUASAR] - 1) < 1e-3


@pytest.mark.parametrize('method', ['drp', 'lstsq'])
def test_rectify_vs_drp_cube(hn3, method):
    """M2 acceptance: spaxel fluxes agree with the DRP reference cube."""
    cube, gpm = hn3[method]
    f1, f0 = spaxel_fluxes(cube, gpm, hn3['ref'], hn3['refgpm'])
    sel = hn3['snr'] > SNR_MIN
    frac = np.abs(f1[sel] / f0[sel] - 1)
    qso = f1[QUASAR] / f0[QUASAR]
    print(f'{method}: {sel.sum()} spaxels with S/N > {SNR_MIN}; median '
          f'|frac| = {np.median(frac):.4f}; 90th pct = '
          f'{np.percentile(frac, 90):.4f}; quasar ratio = {qso:.4f}; '
          f'time = {hn3[f"time_{method}"]} s')
    assert sel.sum() > 1000
    assert np.median(frac) < 0.02
    assert abs(qso - 1) < 0.05


def test_lstsq_vs_drp(hn3):
    """
    M2 acceptance: the two solvers agree.  M3 (task 8): with the
    flux-independent weights of the production ``lstsq`` solver the quasar
    spaxel agrees with ``drp`` to better than 1 %.
    """
    fd, _ = spaxel_fluxes(*hn3['drp'], hn3['ref'], hn3['refgpm'])
    fl, _ = spaxel_fluxes(*hn3['lstsq'], hn3['ref'], hn3['refgpm'])
    sel = hn3['snr'] > SNR_MIN
    frac = np.abs(fl[sel] / fd[sel] - 1)
    qso = fl[QUASAR] / fd[QUASAR]
    print(f'lstsq vs drp: median |frac| = {np.median(frac):.4f}; quasar '
          f'ratio = {qso:.4f}')
    assert np.median(frac) < 0.02
    assert abs(qso - 1) < 0.01


def test_rectify_timing(hn3):
    """M2 acceptance: full-frame run times (machine dependent)."""
    assert hn3['time_drp'] < 60.
    assert hn3['time_lstsq'] < 10.
