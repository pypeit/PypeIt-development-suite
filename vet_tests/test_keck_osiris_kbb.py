"""
Vet tests of the Keck/OSIRIS Kbb/050 science-mode reduction (milestone M4).

They inspect the products of the dev-suite ``keck_osiris/Kbb_050`` reduce
and afterburn tests in ``REDUX_OUT``:

1. the NGC 3245 spec1d (one spectrum per lenslet, OH-refined vacuum
   wavelengths, Davies OH scaling in the sky model);
2. the NGC 3245 datacube written by ``pypeit_fiber_cube`` (lenslet grid,
   WCS referenced to the DRP reference spaxel, the galaxy nucleus inside
   the field);
3. the telluric-corrected A0V standard (``pypeit_tellfit`` on the
   point-source spectrum of HD101060): flat to a few percent.

Tests skip when the products are missing.

Generated by JXP and Claude.
"""
from pathlib import Path

import numpy as np
import pytest

from astropy.io import fits

from pypeit.specobjs import SpecObjs


SCI = 'spec1d_OS.20240203.42705.45-NGC3245*.fits'
CUBE = 'cube_OS.20240203.42705.45-NGC3245*.fits'
TELL = 'spec1d_OS.20240203.59407.32-HD101060*_ps_tellcorr.fits'
BAND = (19650., 23800.)          # Kbb filter (DRP cube range), Angstrom


def find_one(path, pattern):
    """
    Return the single file matching a pattern or skip the test.

    Generated by JXP and Claude.

    Args:
        path (`Path`_): Directory to search.
        pattern (:obj:`str`): Glob pattern.

    Returns:
        `Path`_: The matching file.
    """
    files = sorted(Path(path).glob(pattern))
    if len(files) == 0:
        pytest.skip(f'No {pattern} in {path}')
    return files[0]


@pytest.fixture
def rdx(redux_out):
    """
    The Kbb_050 reduction directory.

    Generated by JXP and Claude.
    """
    return Path(redux_out) / 'keck_osiris' / 'Kbb_050'


def test_spec1d_lenslets(rdx):
    """One spectrum per lenslet with vacuum, OH-refined wavelengths."""
    f = find_one(rdx / 'Science', SCI)
    sobjs = SpecObjs.from_fitsfile(f, chk_version=False)
    hdr = fits.getheader(f)
    ids = np.asarray(sobjs.MASKDEF_ID)
    print(f'{sobjs.nobj} lenslet spectra, AIRORVAC = {hdr["AIRORVAC"]}')
    # Kbb is broadband: 19 lenslet columns x 64 rows, minus lenslets
    # without Keck coefficients
    assert 1150 < sobjs.nobj <= 1216
    assert len(np.unique(ids)) == sobjs.nobj
    assert hdr['AIRORVAC'] == 'vac'
    good = np.concatenate([s.BOX_WAVE[s.BOX_MASK] for s in sobjs])
    assert np.percentile(good, 1) > BAND[0] - 50.
    assert np.percentile(good, 99) < BAND[1] + 50.
    # The Davies OH model is the sky model of the A-B frame (spec2d; the
    # spec1d sky columns hold the sky of the un-subtracted frame): nonzero
    # on the OH-line pixels only, and small compared with the A-B image
    f2 = find_one(rdx / 'Science', SCI.replace('spec1d', 'spec2d'))
    with fits.open(f2) as hdu:
        model = hdu['DET01-SKYMODEL'].data
        sci = hdu['DET01-SCIIMG'].data
    on = model != 0
    print(f'Davies model on {on.mean():.3f} of the pixels, rms '
          f'{np.sqrt(np.mean(model[on]**2)):.1f} counts')
    assert 0.01 < on.mean() < 0.2
    assert np.sqrt(np.mean(model[on]**2)) < 0.1 * np.sqrt(np.mean(sci[on]**2))


def test_cube_structure(rdx):
    """Lenslet-grid cube with the WCS at the DRP reference spaxel."""
    f = find_one(rdx, CUBE)
    with fits.open(f) as hdu:
        cube = hdu['FLUX'].data
        var = hdu['VAR'].data
        h = hdu['FLUX'].header
    print(f'cube {cube.shape}; CRPIX = {h["CRPIX1"]}, {h["CRPIX2"]}; '
          f'scale {h["SPATSCL"]}"')
    # 19 lenslet columns and 64 rows, one padding pixel on each side
    assert cube.shape[1:] == (66, 21)
    assert np.isclose(h['SPATSCL'], 0.05)
    assert h['WCSREF'] == 'origin'
    assert np.isclose(h['CRPIX1'], 12.) and np.isclose(h['CRPIX2'], 32.)
    assert h['WAVEMIN'] > BAND[0] - 100. and h['WAVEMAX'] < BAND[1] + 100.
    assert np.all(np.isfinite(cube)) and np.all(var >= 0)
    # The nucleus of NGC 3245 is well inside the field
    wave = h['WAVEMIN'] + h['WAVESTP'] * np.arange(cube.shape[0])
    img = np.median(cube[(wave > 20500) & (wave < 22800)], axis=0)
    iy, ix = np.unravel_index(np.argmax(img), img.shape)
    print(f'continuum peak at (row, col) = ({iy}, {ix})')
    assert 10 < iy < 56 and 3 < ix < 18
    assert img[iy, ix] > 3 * np.median(img[img > 0])


def test_telluric_flat(rdx):
    """
    The telluric-corrected A0V standard divided by its stellar model is
    flat to a few percent (50-A bins, telluric transmission > 0.5).
    """
    f = find_one(rdx, TELL)
    t = fits.getdata(f, 'SPECTRUM')
    w, fl, m = t['wave'], t['flux'], t['mask'].astype(bool)
    tel, om = t['telluric'], t['obj_model']
    g = m & (tel > 0.5) & (om > 0) & (w > BAND[0]) & (w < BAND[1])
    ratio = fl[g] / om[g]
    edges = np.arange(BAND[0], BAND[1], 50.)
    binned = np.array([np.median(ratio[(w[g] >= lo) & (w[g] < lo + 50)])
                       for lo in edges
                       if np.sum((w[g] >= lo) & (w[g] < lo + 50)) > 5])
    rms = np.std(binned - 1)
    print(f'A0V / model: 50-A binned rms {rms:.3f}, max |dev| '
          f'{np.max(np.abs(binned - 1)):.3f}, {binned.size} bins')
    assert rms < 0.04
    assert np.median(np.abs(binned - 1)) < 0.03
