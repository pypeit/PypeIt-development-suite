"""
Plot the VB_K reid_arxiv: the wavelength range of each archive spectrum
(top) and the stacked OH sky spectra against wavelength (bottom), with
the OH_MOSFIRE_K line positions.

Usage: python plot_vbk_reid.py [archive] [outfile]

Not part of PypeIt.  Generated by JXP and Claude.
"""
import sys

import numpy as np
from astropy.table import Table
from matplotlib import pyplot as plt

from pypeit import dataPaths
from pypeit.core.wavecal import waveio

# Reference palette (dataviz skill), slots 1-2, and neutral inks
COLORS = {1: '#2a78d6', 2: '#eb6834'}
INK, MUTED = '#0b0b0b', '#52514e'


def main():
    """Make the figure.  Generated by JXP and Claude."""
    arxiv = sys.argv[1] if len(sys.argv) > 1 else \
        dataPaths.reid_arxiv.get_file_path('subaru_moircs_VB_K.fits')
    outfile = sys.argv[2] if len(sys.argv) > 2 else 'reid/vbk_reid_arxiv.png'
    tbl = Table.read(arxiv)
    lines = waveio.load_line_lists(['OH_MOSFIRE_K'])[0]['wave']

    fig, (ax1, ax2) = plt.subplots(
        2, 1, figsize=(10, 9), sharex=True,
        gridspec_kw=dict(height_ratios=[1, 2.2], hspace=0.06))
    for ax in (ax1, ax2):
        for s in ('top', 'right'):
            ax.spines[s].set_visible(False)
        ax.tick_params(colors=MUTED)
    nrow = len(tbl)
    for i, row in enumerate(tbl):
        det = int(row['order']) // 10000
        spat = int(row['order']) % 10000
        w = row['wave']
        ax1.plot([w[0], w[-1]], [i, i], color=COLORS[det], lw=4,
                 solid_capstyle='round')
        ax1.text(w[-1] + 30, i, f'{spat}', va='center', fontsize=6,
                 color=MUTED)
        f = row['flux'] / np.percentile(row['flux'], 99.5)
        ax2.plot(w, f * 0.9 + i, color=COLORS[det], lw=0.6)
    for ax in (ax1, ax2):
        ax.vlines(lines, -1, nrow + 0.5, color=MUTED, lw=0.3, alpha=0.4,
                  zorder=0)
    for det in (1, 2):
        ax1.plot([], [], color=COLORS[det], lw=4, label=f'DET0{det}')
    ax1.legend(frameon=False, loc='upper left', fontsize=9,
               labelcolor=INK)
    ax1.set_ylim(-1, nrow)
    ax1.set_yticks([])
    ax1.set_ylabel('archive spectrum', color=INK)
    ax1.set_title(f'subaru_moircs_VB_K.fits: {nrow} OH spectra '
                  f'(grey: OH_MOSFIRE_K lines)', color=INK, fontsize=11)
    ax2.set_ylim(-0.5, nrow + 0.5)
    ax2.set_yticks([])
    ax2.set_ylabel('normalized sky + offset', color=INK)
    ax2.set_xlabel('wavelength (A)', color=INK)
    ax2.set_xlim(18800, 25700)
    fig.savefig(outfile, dpi=130, bbox_inches='tight')
    print(f'Wrote {outfile}')


if __name__ == '__main__':
    main()
