def wavecal(run, det):
    """Return the good wavelength fits of one run and detector.

    Generated by JXP and Claude.

    Args:
        run (str): Reduction directory.
        det (int): Detector.

    Returns:
        list: (spat_id, WaveFit) tuples.
    """
    wc = WaveCalib.from_file(
        Path(run) / 'Calibrations' / f'WaveCalib_A_0_DET0{det}.fits',
        chk_version=False)
    return [(s, w) for s, w in zip(wc.spat_ids, wc.wv_fits)
            if w is not None and w.pypeitfit is not None]


def fig_rms():
    """Wavelength rms per slit, run1 vs run2.

    Generated by JXP and Claude."""
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.4), sharey=True)
    for ax, det in zip(axes, [1, 2]):
        for run, c, m, lab in [('run1', C2, 'o', 'run1: OH_NIRES'),
                               ('run2', C1, 's', 'run2: OH_MOSFIRE_K')]:
            fits = wavecal(run, det)
            x = np.arange(len(fits))
            ax.plot(x, [w.rms for _, w in fits], m, color=c, ms=7,
                    mec=SURF, mew=1.5, label=lab)
        ax.set_xticks(x, [str(s) for s, _ in fits], rotation=60,
                      fontsize=8)
        ax.set_title(f'DET0{det}', loc='left', fontsize=11)
        ax.set_xlabel('slit (spat_id)')
    axes[0].set_ylabel('wavelength fit rms (px)')
    axes[0].set_ylim(0, 0.55)
    axes[1].legend(loc='upper right')
    fig.tight_layout()
    fig.savefig(OUT / 'wave_rms.png', dpi=130)


def fig_coverage():
    """Wavelength range per slit: full solution and fitted lines.

    Generated by JXP and Claude."""
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.2), sharex=True)
    for ax, det in zip(axes, [1, 2]):
        fits = wavecal('run2', det)
        for i, (s, w) in enumerate(fits):
            ax.plot([w.wave_soln[0] / 1e4, w.wave_soln[-1] / 1e4], [i, i],
                    color=C1, lw=2, alpha=0.35, solid_capstyle='round')
            ax.plot([w.wave_fit.min() / 1e4, w.wave_fit.max() / 1e4],
                    [i, i], color=C1, lw=6, solid_capstyle='butt')
        ax.set_yticks(range(len(fits)), [str(s) for s, _ in fits],
                      fontsize=8)
        ax.axvline(2.499, color=INK2, lw=1, ls='--')
        ax.text(2.503, len(fits) - 0.6, 'end of OH list', fontsize=8,
                color=INK2)
        ax.set_title(f'DET0{det}', loc='left', fontsize=11)
        ax.set_xlabel('wavelength (um)')
        ax.grid(axis='y', visible=False)
    axes[0].set_ylabel('slit (spat_id)')
    axes[0].set_xlim(1.85, 2.6)
    fig.text(0.01, 0.01, 'thick: range of fitted OH lines; thin: full '
             'solution (extrapolated beyond the thick part)',
             fontsize=8, color=INK2)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(OUT / 'wave_coverage.png', dpi=130)


def fig_std_offset():
    """Standard minus science OH line offset vs slit position.

    Generated by JXP and Claude."""
    txt = Path('std_oh_offset_run2.txt').read_text().splitlines()
    data = {}
    for line, nxt in zip(txt[::2], txt[1::2]):
        det, frame = line.split()[0], line.split()[1].rstrip(':')
        pairs = re.findall(r'(\d+):([+-]\d+\.\d+)', nxt)
        data.setdefault(det, []).append(
            (frame, np.array([[int(a), float(b)] for a, b in pairs])))
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.4), sharey=True)
    marks = ['o', 's', '^', 'D']
    for ax, det in zip(axes, ['DET01', 'DET02']):
        allx = []
        for k, (frame, d) in enumerate(data[det]):
            ax.plot(d[:, 0], d[:, 1], marks[k], color=C1 if k < 2 else C2,
                    ms=6, mec=SURF, mew=1,
                    label=('std1 ' if k < 2 else 'std2 ') + frame[4:12])
            allx.append(d)
        d = np.vstack(allx)
        p = np.polyfit(d[:, 0], d[:, 1], 1)
        xx = np.array([0, 2040])
        ax.plot(xx, np.polyval(p, xx), color=INK2, lw=1)
        ax.axhline(0, color=INK, lw=0.8)
        ax.set_title(f'{det}: slope {p[0] * 1000:+.2f} px / 1000 px',
                     loc='left', fontsize=11)
        ax.set_xlabel('slit position (spat_id, px)')
    for sid, lab in [(337, 'std1 star'), (469, 'std2 star')]:
        axes[0].axvline(sid, color=C3, lw=1, ls=':')
        axes[0].text(sid + 15, 0.55, lab, fontsize=8, color=INK2,
                     rotation=90, va='top')
    axes[0].set_ylabel('standard - science OH (px)')
    axes[1].legend(fontsize=8, loc='upper left')
    fig.tight_layout()
    fig.savefig(OUT / 'std_oh_offset.png', dpi=130)


def fig_spectra():
    """Extracted science object and standard-star spectra.

    Generated by JXP and Claude."""
    sci = sorted(Path('run2/Science').glob('spec1d_MCSA00352031*.fits'))[0]
    fig, axes = plt.subplots(2, 1, figsize=(10, 6.2))
    sobjs = specobjs.SpecObjs.from_fitsfile(sci, chk_version=False)
    so = sobjs[sobjs.SLITID == 469][0]
    w, f = so.OPT_WAVE, so.OPT_COUNTS
    sig = np.where(so.OPT_COUNTS_IVAR > 0,
                   1 / np.sqrt(np.clip(so.OPT_COUNTS_IVAR, 1e-30, None)),
                   np.nan)
    sm = ndimage.median_filter(f, 9)
    axes[0].plot(w / 1e4, f, color=GRID, lw=0.6, label='per pixel')
    axes[0].plot(w / 1e4, sm, color=C1, lw=1.5, label='9-px median')
    axes[0].plot(w / 1e4, sig, color=C2, lw=0.8, label='1-sigma noise')
    axes[0].set_ylim(np.nanpercentile(f, 1) * 1.2,
                     np.nanpercentile(f, 99.5) * 1.2)
    axes[0].set_title(f'Science {so.NAME} (MCSA00352031, optimal)',
                      loc='left', fontsize=11)
    axes[0].set_ylabel('counts')
    axes[0].legend(fontsize=8, ncol=3, loc='upper left')
    # The stars, by name (the highest-S/N object of std1 A is a
    # sky-subtraction artefact at the slit edge, SPAT0289)
    stars = [('MCSA00352125', 'SPAT0360-SLIT0337-DET01', C1, '-',
              'std1 A (slit 337)'),
             ('MCSA00352127', 'SPAT0318-SLIT0337-DET01', C1, ':',
              'std1 B (slit 337)'),
             ('MCSA00352141', 'SPAT0490-SLIT0469-DET01', C2, '-',
              'std2 A (slit 469)'),
             ('MCSA00352143', 'SPAT0447-SLIT0469-DET01', C2, ':',
              'std2 B (slit 469)'),
             ('MCSA00352125', 'SPAT0289-SLIT0337-DET01', INK2, '--',
              'std1 A artefact (SPAT0289)')]
    for frame, name, c, ls, lab in stars:
        f1 = sorted(Path('run2/Science').glob(f'spec1d_{frame}*.fits'))[0]
        sobjs = specobjs.SpecObjs.from_fitsfile(f1, chk_version=False)
        so = [o for o in sobjs if o.NAME == name][0]
        axes[1].plot(so.OPT_WAVE / 1e4, so.OPT_COUNTS, color=c, ls=ls,
                     lw=1, label=f'{lab}, S/N {so.S2N:.0f}')
    axes[1].set_title('Standard HIP59174 (optimal extraction, counts)',
                      loc='left', fontsize=11)
    axes[1].set_ylabel('counts')
    axes[1].legend(fontsize=8, loc='upper right', ncol=2)
    for ax in axes:
        ax.set_xlim(1.88, 2.56)
        ax.set_xlabel('wavelength (um)')
    fig.tight_layout()
    fig.savefig(OUT / 'spectra.png', dpi=130)


def fig_sci_minus_sky():
    """Smoothed (sci - sky)/sigma maps of the first science frame.

    Generated by JXP and Claude."""
    f = sorted(Path('run2/Science').glob('spec2d_MCSA00352031*.fits'))[0]
    fig, axes = plt.subplots(1, 2, figsize=(10, 5.2))
    for ax, det in zip(axes, ['DET01', 'DET02']):
        s = spec2dobj.Spec2DObj.from_file(f, det, chk_version=False)
        good = (s.bpmmask.mask == 0) & (s.slits.slit_img() >= 0)
        r = np.where(good, (s.sciimg - s.skymodel) * np.sqrt(s.ivarmodel),
                     0)
        ax.imshow(ndimage.gaussian_filter(r, [3, 2]), origin='lower',
                  cmap='gray', vmin=-0.8, vmax=0.8, aspect='auto')
        ax.set_title(f'{det}', loc='left', fontsize=11)
        ax.set_xlabel('spatial (px)')
        ax.grid(False)
    axes[0].set_ylabel('spectral (px)')
    fig.tight_layout()
    fig.savefig(OUT / 'sci_minus_sky.png', dpi=110)


def copy_small(src, name, width=1400):
    """Copy a PNG, downscaled to at most ``width`` pixels wide.

    Generated by JXP and Claude.

    Args:
        src (str): Source file.
        name (str): Output name in OUT.
        width (int): Maximum width.
    """
    im = Image.open(src)
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)),
                       Image.LANCZOS)
    im.convert('RGB').save(OUT / name, optimize=True)


