"""
Check the dome-flat ratio F2/F1 against the night sky.

Both MOIRCS channels are exposed at the same time, and the night sky
(OH lines plus thermal continuum) fills both fields evenly through the
telescope.  The ratio of the sky counts per Angstrom of the two detectors
is therefore an independent measure of the channel throughput ratio, free
of the dome-screen illumination.  The sky image is the run's processed
science-frame stack (``Arc_<key>_DET0N.fits``; the OH frames are the arcs).

Usage::

    python sky_ratio_check.py run5 flux/sky_ratio

Writes ``<outroot>.png`` and ``<outroot>.txt`` (binned ratios).

Generated by JXP and Claude
"""

import argparse
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

from pypeit.flatfield import FlatImages
from pypeit.images.buildimage import ArcImage
from pypeit.slittrace import SlitTraceSet

from transfer_sensfunc import (average_flat_spectrum, collapse_slits,
                               flat_ratio)


def binned_ratio(wave, num, den, edges, min_frac=0.8):
    """
    Ratio of sums of two spectra in wavelength bins.

    Args:
        wave (`numpy.ndarray`_):
            Common wavelength grid.
        num, den (`numpy.ndarray`_):
            Spectra on ``wave`` (NaN where undefined).
        edges (`numpy.ndarray`_):
            Bin edges.
        min_frac (:obj:`float`, optional):
            Minimum fraction of defined grid points in a bin.

    Returns:
        `numpy.ndarray`_: Ratio per bin (NaN if the bin is too empty).

    Generated by JXP and Claude
    """
    out = np.full(edges.size - 1, np.nan)
    for i in range(edges.size - 1):
        inbin = (wave >= edges[i]) & (wave < edges[i + 1])
        ok = inbin & np.isfinite(num) & np.isfinite(den)
        if ok.sum() >= min_frac * inbin.sum() and ok.sum() > 0:
            out[i] = np.sum(num[ok]) / np.sum(den[ok])
    return out


def main():
    """
    Command-line entry point; see the module docstring.

    Generated by JXP and Claude
    """
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    parser.add_argument('rundir')
    parser.add_argument('outroot')
    parser.add_argument('--calib-key', default='A_0')
    parser.add_argument('--bin', type=float, default=100.,
                        help='bin width (Angstrom)')
    args = parser.parse_args()

    cdir = Path(args.rundir) / 'Calibrations'
    sky, flat, slits = {}, {}, {}
    for det in [1, 2]:
        sfx = f'{args.calib_key}_DET{det:02d}'
        flat[det] = FlatImages.from_file(cdir / f'Flat_{sfx}.fits',
                                         chk_version=False)
        slits[det] = SlitTraceSet.from_file(cdir / f'Slits_{sfx}.fits.gz',
                                            chk_version=False)
        arc = ArcImage.from_file(cdir / f'Arc_{sfx}.fits',
                                 chk_version=False)
        sky[det] = collapse_slits(arc.image, flat[det].pixelflat_waveimg,
                                  slits[det])

    # Dome flat ratio (as in transfer_sensfunc.py) and the same for the sky
    fr = flat_ratio(flat[1], slits[1], flat[2], slits[2])
    wave = fr['wave']
    s1, n1, a1 = average_flat_spectrum(wave, sky[1])
    s2, n2, a2 = average_flat_spectrum(wave, sky[2])
    gpm = fr['gpm']
    edges = np.arange(np.ceil(wave[gpm].min() / args.bin) * args.bin,
                      wave[gpm].max(), args.bin)
    cen = 0.5 * (edges[1:] + edges[:-1])
    s1g, s2g = np.where(gpm, s1, np.nan), np.where(gpm, s2, np.nan)
    r_sky = binned_ratio(wave, s2g, s1g, edges)
    f1g = np.where(gpm, fr['flux_source'], np.nan)
    f2g = np.where(gpm, fr['flux_target'], np.nan)
    r_flat = binned_ratio(wave, f2g, f1g, edges)
    nmin = np.array([min(fr['nslit_source'][(wave >= lo) & (wave < hi)].min(),
                         fr['nslit_target'][(wave >= lo) & (wave < hi)].min())
                     for lo, hi in zip(edges[:-1], edges[1:])])

    # Summary over the well-sampled part (>= 3 slits per detector)
    good = (nmin >= 3) & np.isfinite(r_sky) & np.isfinite(r_flat)
    q = r_sky[good] / r_flat[good]
    print(f'bins with >= 3 slits per detector: {good.sum()} '
          f'({edges[:-1][good].min():.0f}-{edges[1:][good].max():.0f} A)')
    print(f'  flat F2/F1: median {np.median(r_flat[good]):.3f}, '
          f'range {r_flat[good].min():.3f}-{r_flat[good].max():.3f}')
    print(f'  sky  S2/S1: median {np.median(r_sky[good]):.3f}, '
          f'range {r_sky[good].min():.3f}-{r_sky[good].max():.3f}')
    print(f'  sky/flat: median {np.median(q):.3f}, '
          f'std {np.std(q):.3f}, range {q.min():.3f}-{q.max():.3f}')
    print('  sky slit scales DET01', np.round(a1, 3))
    print('  sky slit scales DET02', np.round(a2, 3))
    print('  flat slit scales DET01', np.round(fr['scales_source'], 3))
    print('  flat slit scales DET02', np.round(fr['scales_target'], 3))

    np.savetxt(f'{args.outroot}.txt',
               np.column_stack([cen, nmin, r_flat, r_sky]),
               fmt='%.0f %d %.4f %.4f',
               header='wave_center min_nslit R_flat R_sky')
    fig, ax = plt.subplots(2, 1, figsize=(9, 7), sharex=True)
    ax[0].plot(wave / 1e4, s1, lw=0.4, label='sky DET01')
    ax[0].plot(wave / 1e4, s2, lw=0.4, label='sky DET02')
    ax[0].set_yscale('log')
    ax[0].set_ylabel('sky counts / A / pix')
    ax[0].legend()
    ax[1].plot(wave / 1e4, fr['ratio'], color='k', lw=1,
               label='flat F2/F1 (smoothed)')
    ax[1].plot(cen / 1e4, r_flat, 'ks', ms=4, mfc='none',
               label=f'flat, {args.bin:.0f} A bins')
    ax[1].plot(cen / 1e4, r_sky, 'o', color='C3', ms=4,
               label=f'sky S2/S1, {args.bin:.0f} A bins')
    ax[1].plot(cen[nmin < 3] / 1e4, r_sky[nmin < 3], 'o', color='0.7',
               ms=4, label='< 3 slits per detector')
    ax[1].set_ylim(1.0, 1.5)
    ax[1].set_ylabel('DET02 / DET01')
    ax[1].set_xlabel('wavelength (um)')
    ax[1].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(f'{args.outroot}.png', dpi=120)


if __name__ == '__main__':
    main()
