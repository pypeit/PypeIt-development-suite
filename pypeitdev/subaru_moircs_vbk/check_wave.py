"""Summarize slits and wavelength solutions per detector.

Usage: python check_wave.py <redux_dir>

For each slit: spat_id, BOXSLIT/bad flags, rms (px), number of lines,
the wavelengths at the first, middle, and last spectral pixel, and
whether the solution increases monotonically along the spectral axis.

Generated by JXP and Claude (dev script, not part of PypeIt).
"""
import sys
from pathlib import Path

import numpy as np

from pypeit.wavecalib import WaveCalib
from pypeit.slittrace import SlitTraceSet

redux = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
for f in sorted((redux / 'Calibrations').glob('WaveCalib_*')):
    wc = WaveCalib.from_file(f, chk_version=False)
    slits = SlitTraceSet.from_file(
        str(f).replace('WaveCalib', 'Slits') + '.gz', chk_version=False)
    flags = slits.bitmask.flagged_bits
    ngood = 0
    print(f.name, 'nslits', slits.nslits)
    for i, ws in enumerate(wc.wv_fits):
        fl = ','.join(flags(slits.mask[i])) or '-'
        if ws is None or ws.pypeitfit is None:
            print(f'  slit {slits.spat_id[i]:5d} {fl:20s} no fit')
            continue
        x = np.linspace(0., 1., 2040)
        w = ws.pypeitfit.eval(x)
        mono = 'incr' if np.all(np.diff(w) > 0) else \
            ('decr' if np.all(np.diff(w) < 0) else 'NONMONO')
        ngood += 1
        print(f'  slit {slits.spat_id[i]:5d} {fl:20s} rms={ws.rms:.3f} '
              f'nlin={len(ws.pixel_fit):3d} '
              f'wave(0,mid,end)={np.round(w[[0, 1020, -1]], 0)} {mono} '
              f'disp={np.median(np.diff(w)):.3f}')
    print(f'  solved: {ngood}')
