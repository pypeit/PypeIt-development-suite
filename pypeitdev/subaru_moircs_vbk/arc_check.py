"""Check the VB_K OH wavelength solution with the evening ThAr arcs.

Usage: python arc_check.py <redux_dir> [outdir]

PypeIt has no K-band Th line list, and the ThAr frames are untyped in
the PypeIt file, so no arc products are made from them.  Instead:

1. Build the arc image of each detector from the 4 ThAr frames
   (``buildimage_fromlist``, with the arc-frame processing of the run,
   but a plain mean: ``clip = False``).  The lamp lights a different
   part of the mask in each frame, so the default sigma-clipped mean
   rejects the bright frames on the lines and distorts the profiles
   (up to 2.7 px shifts).  Each frame is also measured on its own.
2. For each solved science slit, collapse the central 60% of the slit
   along the run's tilts onto the slit-centre spectral coordinate (the
   coordinate of the OH wavelength solution), so the whole slit width
   contributes and the line tilts do not broaden the lines.
3. Predict where the Ar lines of ``Ar_IR_MOSFIRE`` fall with the OH
   solution and measure them in the continuum-subtracted spectrum
   (continuum from PypeIt's ``detect_lines``).  The lines (Ar and OH)
   are flat-topped (the image of the ~6 px slit), so a Gaussian fit to
   the top (``detect_lines``) is unstable on the bright ThAr lines and
   often splits a line into two peaks.  Each line is measured instead
   by its first moment within +-7 px, iterated from the highest pixel
   near the prediction.  A
   first pass (+-4 px) gives the median offset per chip; the second
   pass searches +-1.5 px around it.  A line is kept if its peak is
   >= 8 sigma and no other line within 10-18 px exceeds 15% of its peak
   (blends with unlisted Th lines).
4. Control: the science sky (frame A) goes through the same steps
   with the OH lines used in the fit, so the method itself should give
   ~0 offset there.
5. Per chip: the trend with wavelength within slits, a fit of the slit
   median offsets with a line in the slit's spatial position (shift
   plus rotation, as for the standards), and the agreement between the
   single frames.  ``arc_vs_spat.png`` adds the standards' OH offsets
   from ``std_oh_offset_run2.txt``.

Writes ``<outdir>/arc_offsets.txt`` (one row per measured line and
image: ``mean`` or a single frame ``f0``-``f3``), ``arc_oh_control.txt``,
``arc_summary.txt``, and the figures ``arc_offsets.png``,
``arc_profiles.png`` and ``arc_vs_spat.png``.

Not part of PypeIt.  Generated by JXP and Claude.
"""
