"""
Focused test of reidentify parameters on DET01 slit 758, the one slit
whose leave-one-out and cross-detector solutions are wrong at the red
end.  Runs the variants in parallel.

Usage: python tune_reid_758.py <redux_dir> [loo|xdet] [2]

Not part of PypeIt.  Generated by JXP and Claude.
"""
import os
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np

import make_vbk_reid
import test_reid as T
from pypeit.wavecalib import WaveCalib

REDUX = Path(sys.argv[1])
MODE = sys.argv[2] if len(sys.argv) > 2 else 'loo'
VARIANTS = [{}, {'n_final': 3}, {'cc_local_thresh': 0.8},
            {'cc_local_thresh': 0.9}, {'match_toler': 1.0},
            {'stretch_func': 'linear'}, {'nlocal_cc': 21},
            {'sigdetect': 10.}, {'cc_thresh': 0.8}]
if len(sys.argv) > 3 and sys.argv[3] == '2':
    # Second round
    VARIANTS = [{'reid_cont_sub': False}, {'cc_percent_ceil': 90.},
                {'sigdetect': 3.}, {'cc_thresh': 0.85}, {'cc_thresh': 0.88},
                {'nlocal_cc': 31}, {'match_toler': 0.5},
                {'cc_thresh': 0.8, 'match_toler': 1.0},
                {'n_final': 5}]


def one(kw):
    """Solve slit 758 with one variant.  Generated by JXP and Claude."""
    hg = WaveCalib.from_file(
        REDUX / 'Calibrations' / 'WaveCalib_A_0_DET01.fits',
        chk_version=False)
    i = [k for k, w in enumerate(hg.wv_fits)
         if w is not None and w.spat_id == 758][0]
    fn = T.HERE / 'reid' / f'vbk_758_{os.getpid()}.fits'
    dets = [1, 2] if MODE == 'loo' else [2]
    rows = make_vbk_reid.select_rows(REDUX, dets, exclude=[10758],
                                     verbose=False)
    make_vbk_reid.write_arxiv(rows, fn)
    c = T.compare(hg, i, T.run_reid(hg, 1, fn, [i], kw).get(str(i)))
    fn.unlink()
    return kw, c


if __name__ == '__main__':
    with Pool(len(VARIANTS)) as p:
        for kw, c in p.map(one, VARIANTS):
            if c['rms'] is None:
                print(f'{MODE} {kw}: no fit')
                continue
            print(f'{MODE} {str(kw):28s} rms {c["rms"]:.3f} n {c["nlin"]:3d}'
                  f' med|dl| {c["dmed"]:.2f} max|dl| {c["dmax"]:.2f} '
                  f'{"GOOD" if c["good"] else "BAD"}')
