"""
Figures for the summary of the full science set (2D coadd and lines).

Two coadds can be shown (``--variant``): ``header`` (``coadd2d/``,
header dither offsets, uniform weights; figures in ``lines/``) and
``bright`` (``coadd2d_bright/``, offsets and weights from the DET01
target; figures in ``lines_bright/``).  Writes:

- ``stamps_selected.png``: postage stamps (matched-filter S/N) and 1D
  boxcar spectra of the candidates kept after the visual check;
- ``target_1d.png``: the 1D spectrum of the DET01 target from the 2D
  coadd (counts, optimal extraction), lightly smoothed;
- ``drift.png`` (``bright`` only): the target's position in each frame
  and the coadd offsets from the target and from the headers.

Usage::

    python make_summary_figs.py --variant bright

Generated by JXP and Claude
"""

