"""
QA of a spliced MOIRCS VB_K sensitivity function.

Reports, for each standard star spectrum in the sens file: the wavelength
range, the fitted telluric parameters, and the effective wavelength
offset of the telluric model (shift plus stretch, converted to MOIRCS
pixels); then the zeropoints of the two standards in their overlap, the
splice, and the residuals of the fluxed standard against the stellar
model, inside and outside the telluric bands.

Usage::

    python sensfunc_check.py flux/sens_A2/sens_HIP59174_A2.fits flux/qa_A2

Generated by JXP and Claude
"""

import argparse

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

from pypeit.core import telluric
from pypeit.sensfunc import SensFunc

# Dispersion of VB_K (A/pix) used to express offsets in detector pixels
DISP = 1.95


def telluric_offset(sens):
    """
    Effective wavelength offset of the fitted telluric model.

    The telluric model is evaluated on a log-lambda grid shifted by
    ``shift * dloglam`` and stretched by ``stretch`` about the start of the
    padded fitting range (:func:`pypeit.core.telluric.shift_telluric`).
    The model value at lambda is that of the unshifted model at
    lambda + offset, so a positive offset moves the absorption bands to
    the blue.

    Args:
        sens (:class:`~pypeit.sensfunc.SensFunc`):
            Sensitivity function with a grid- or PCA-based telluric
            model.

    Returns:
        :obj:`list`: One (wave, offset in Angstrom) tuple per standard.

    Generated by JXP and Claude
    """
    tm = sens.telluric.model
    wmin = np.min(tm['WAVE_MIN'])
    wmax = np.max(tm['WAVE_MAX'])
    # Same trimmed grid as in Telluric.__init__ (file name, not a path)
    read = telluric.read_telluric_pca if sens.telluric.teltype == 'pca' \
        else telluric.read_telluric_grid
    td = read(sens.telluric.telgrid, wave_min=wmin, wave_max=wmax)
    grid = td['wave_grid']
    # The fitted index range must map onto each spectrum's own range
    for k in range(len(tm)):
        ends = grid[[int(tm['IND_LOWER'][k]), int(tm['IND_UPPER'][k])]]
        if np.any(np.abs(ends - [tm['WAVE_MIN'][k], tm['WAVE_MAX'][k]])
                  > 2 * np.median(np.diff(grid))):
            raise ValueError('Could not rebuild the telluric grid.')
    out = []
    for k in range(len(tm)):
        lo = int(tm['IND_LOWER'][k])
        hi = int(tm['IND_UPPER'][k])
        lo_pad = max(lo - td['tell_pad_pix'], 0)
        idx = np.arange(lo, hi + 1)
        dlog = ((idx - lo_pad) * td['dloglam'] * (tm['TELL_STRETCH'][k] - 1)
                + tm['TELL_SHIFT'][k] * td['dloglam'])
        wave = grid[idx]
        out += [(wave, wave * np.log(10.) * dlog)]
    return out


def main():
    """
    Command-line entry point; see the module docstring.

    Generated by JXP and Claude
    """
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    parser.add_argument('sensfile')
    parser.add_argument('outroot')
    args = parser.parse_args()

    sens = SensFunc.from_file(args.sensfile, chk_version=False)
    st = sens.sens
    tm = sens.telluric.model
    nstd = len(st)
    print(f'{args.sensfile}: {nstd} spectra, spliced grid '
          f'{sens.wave[sens.wave > 1].min():.0f}-'
          f'{sens.wave.max():.0f} A')
    offsets = telluric_offset(sens)
    for k in range(nstd):
        w, off = offsets[k]
        print(f'  [{k}] {st["WAVE_MIN"][k]:.0f}-{st["WAVE_MAX"][k]:.0f} A:'
              f' resln {tm["TELL_RESLN"][k]:.0f}, shift '
              f'{tm["TELL_SHIFT"][k]:.2f} grid px, stretch '
              f'{tm["TELL_STRETCH"][k]:.5f}, chi2 {tm["CHI2"][k]:.0f}')
        print(f'      telluric model offset {off[0]:+.2f} A at {w[0]:.0f}'
              f', {np.interp(w.mean(), w, off):+.2f} A at {w.mean():.0f}'
              f', {off[-1]:+.2f} A at {w[-1]:.0f} A '
              f'({off[0] / DISP:+.2f} to {off[-1] / DISP:+.2f} px)')
        print(f'      telluric parameters (grid: pressure, temperature, '
              f'humidity, "airmass" axis; pca: coefficients) '
              f'{np.round(tm["TELL_THETA"][k][:-3], 2)}')

    # Zeropoints of the standards on the spliced grid
    wsp = sens.wave[:, 0]
    gsp = wsp > 1.0
    zps = []
    for k in range(nstd):
        w = st['SENS_WAVE'][k]
        z = st['SENS_ZEROPOINT_FIT'][k]
        ok = (w >= st['WAVE_MIN'][k]) & (w <= st['WAVE_MAX'][k]) & (w > 1)
        zps += [(w[ok], z[ok])]
    # Overlap of the first two (blue, red)
    lo = st['WAVE_MIN'][1]
    hi = st['WAVE_MAX'][0]
    print(f'  overlap {lo:.0f}-{hi:.0f} A: zp(red std) - zp(blue std)')
    for a, b in [(lo, lo + 300), (lo + 300, lo + 700), (lo + 700, hi - 400),
                 (hi - 400, hi)]:
        x = np.linspace(a, b, 50)
        d = np.interp(x, *zps[1]) - np.interp(x, *zps[0])
        print(f'    {a:.0f}-{b:.0f}: {np.mean(d):+.3f} mag '
              f'({10**(0.4 * np.mean(d)) - 1:+.1%} in flux)')
    # Jump of the spliced zeropoint at the splice point
    i = np.searchsorted(wsp, lo)
    print(f'  splice: zp {sens.zeropoint[i - 2, 0]:.3f} at '
          f'{wsp[i - 2]:.0f} -> {sens.zeropoint[i + 1, 0]:.3f} at '
          f'{wsp[i + 1]:.0f} A')

    # Fluxed standard / stellar model, inside and outside telluric bands
    fig, ax = plt.subplots(3, 1, figsize=(10, 10), sharex=True)
    for k in range(nstd):
        w = st['SENS_FLUXED_STD_WAVE'][k]
        f = st['SENS_FLUXED_STD_FLAM'][k]
        m = st['SENS_STD_MODEL_FLAM'][k]
        g = st['SENS_FLUXED_STD_MASK'][k].astype(bool) & (w > 1) & (m > 0)
        tell = np.interp(w, tm['WAVE'][k], tm['TELLURIC'][k])
        r = f[g] / m[g]
        deep = tell[g] < 0.8
        clear = tell[g] > 0.95
        print(f'  [{k}] fluxed std / model: median {np.median(r):.3f}; '
              f'telluric > 0.95: std {np.std(r[clear]):.3f}; '
              f'< 0.8: std {np.std(r[deep]):.3f} '
              f'({deep.sum()} px)')
        brg = g & (np.abs(w - 21661) < 40)
        if brg.sum() > 5:
            print(f'      Br-gamma (21661 +- 40 A): fluxed/model min '
                  f'{np.min(f[brg] / m[brg]):.3f}, mean '
                  f'{np.mean(f[brg] / m[brg]):.3f}')
        ax[0].plot(w[g] / 1e4, f[g], lw=0.6, label=f'fluxed std [{k}]')
        ax[0].plot(w[g] / 1e4, m[g], 'k', lw=0.6)
        ax[1].plot(w[g] / 1e4, r, lw=0.6, label=f'[{k}]')
    for k in range(nstd):
        ax[2].plot(zps[k][0] / 1e4, zps[k][1], lw=1,
                   label=f'zeropoint fit [{k}]')
    ax[2].plot(wsp[gsp] / 1e4, sens.zeropoint[gsp, 0], 'k--', lw=0.8,
               label='spliced')
    ax[0].set_ylabel('F_lambda (1e-17 cgs)')
    ax[0].legend(fontsize=8)
    ax[1].axhline(1, color='k', lw=0.5)
    ax[1].set_ylim(0.8, 1.2)
    ax[1].set_ylabel('fluxed std / model')
    ax[1].legend(fontsize=8)
    # The spliced array ends in zeros (masked in fluxing); keep them out
    zok = sens.zeropoint[gsp, 0] > 5
    ax[2].set_ylim(sens.zeropoint[gsp, 0][zok].min() - 0.2,
                   sens.zeropoint[gsp, 0][zok].max() + 0.2)
    ax[2].set_ylabel('zeropoint (mag)')
    ax[2].set_xlabel('wavelength (um)')
    ax[2].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(f'{args.outroot}.png', dpi=120)

    # Telluric model offset along each spectrum
    fig, ax = plt.subplots(figsize=(8, 3.5))
    for k in range(nstd):
        w, off = offsets[k]
        ax.plot(w / 1e4, off / DISP, label=f'[{k}]')
    ax.axhline(0, color='k', lw=0.5)
    ax.set_xlabel('wavelength (um)')
    ax.set_ylabel('telluric offset (MOIRCS px)')
    ax.legend()
    fig.tight_layout()
    fig.savefig(f'{args.outroot}_telluric_offset.png', dpi=120)


if __name__ == '__main__':
    main()
