"""
Where does light actually reach the detector in VB_K?  Extract the
processed lamp-on minus lamp-off dome flat (``pixelflat_raw``) along the
centre of each science slit, put it on the slit's wavelength solution,
and find where the signal falls at the blue and red ends.  The halogen
lamp spectrum is smooth, so sharp drops mark the transmission edges of
the filters (FILTER02 = OC1_3, FILTER03 = VB_K) and the grism.

Usage: python flat_coverage.py <redux_dir> [outfile.png]

Prints, per slit, the wavelength range on the detector and the
wavelengths where the flat falls to 50% and 10% of its peak at each end
(None if it does not fall that far within the slit's range).

Not part of PypeIt.  Generated by JXP and Claude.
"""
import sys
from pathlib import Path

import numpy as np
from matplotlib import pyplot as plt

from pypeit.flatfield import FlatImages
from pypeit.slittrace import SlitTraceSet
from pypeit.wavecalib import WaveCalib

COLORS = {1: '#2a78d6', 2: '#eb6834'}


def slit_spectra(redux, det):
    """
    Flat spectrum along the centre of each solved science slit.

    Generated by JXP and Claude.

    Args:
        redux (Path): Reduction directory.
        det (int): Detector.

    Returns:
        list: dicts with spat, wave, flux (median of 5 central columns).
    """
    cal = redux / 'Calibrations'
    flat = FlatImages.from_file(cal / f'Flat_A_0_DET0{det}.fits',
                                chk_version=False)
    slits = SlitTraceSet.from_file(cal / f'Slits_A_0_DET0{det}.fits.gz',
                                   chk_version=False)
    wc = WaveCalib.from_file(cal / f'WaveCalib_A_0_DET0{det}.fits',
                             chk_version=False)
    img = flat.pixelflat_raw
    left, right, _ = slits.select_edges()
    out = []
    for i, w in enumerate(wc.wv_fits):
        if w is None or w.pypeitfit is None:
            continue
        cen = np.round((left[:, i] + right[:, i]) / 2).astype(int)
        rows = np.arange(img.shape[0])
        cols = np.clip(cen[:, None] + np.arange(-2, 3)[None, :], 0,
                       img.shape[1] - 1)
        flux = np.median(img[rows[:, None], cols], axis=1)
        out.append(dict(spat=int(w.spat_id), wave=w.wave_soln, flux=flux))
    return out


def edge(wave, flux, frac, side):
    """
    Wavelength where a smoothed flux falls to a fraction of its peak,
    searching outward from the peak.

    Generated by JXP and Claude.

    Args:
        wave, flux (`numpy.ndarray`_): Spectrum.
        frac (float): Fraction of the peak.
        side (str): 'blue' or 'red'.

    Returns:
        float or None: Wavelength (A), or None if not reached.
    """
    k = 15
    sm = np.convolve(flux, np.ones(k) / k, mode='same')
    sm[:k] = sm[k]
    sm[-k:] = sm[-k - 1]
    ip = int(np.argmax(sm))
    thr = frac * sm[ip]
    idx = np.arange(ip, -1, -1) if side == 'blue' else np.arange(ip, sm.size)
    below = idx[sm[idx] < thr]
    return None if below.size == 0 else float(wave[below[0]])


def main():
    """Print the edges and make the figure.  Generated by JXP and
    Claude."""
    redux = Path(sys.argv[1])
    outfile = sys.argv[2] if len(sys.argv) > 2 else 'flat_coverage.png'
    fig, ax = plt.subplots(figsize=(10, 5.5))
    fmt = lambda v: '   none' if v is None else f'{v:7.0f}'
    print('det spat   range (A)   | blue 10%  50% | red 50%  10%')
    for det in [1, 2]:
        for s in slit_spectra(redux, det):
            w, f = s['wave'], s['flux']
            print(f"  {det} {s['spat']:5d} {w[0]:6.0f}-{w[-1]:6.0f} | "
                  f"{fmt(edge(w, f, 0.1, 'blue'))} "
                  f"{fmt(edge(w, f, 0.5, 'blue'))} | "
                  f"{fmt(edge(w, f, 0.5, 'red'))} "
                  f"{fmt(edge(w, f, 0.1, 'red'))}")
            ax.plot(w / 1e4, f / np.nanpercentile(f, 99), lw=0.7,
                    color=COLORS[det], alpha=0.8)
    for det in [1, 2]:
        ax.plot([], [], color=COLORS[det], label=f'DET0{det}')
    ax.set_xlabel('Wavelength (um)')
    ax.set_ylabel('dome flat (lamp on - off), / 99th percentile')
    ax.set_title('VB_K dome flat along each science slit (FILTER02 OC1_3, '
                 'FILTER03 VB_K)')
    ax.legend(frameon=False)
    ax.set_ylim(-0.05, 1.15)
    for sp in ('top', 'right'):
        ax.spines[sp].set_visible(False)
    fig.savefig(outfile, dpi=130, bbox_inches='tight')
    print(f'Wrote {outfile}')


if __name__ == '__main__':
    main()
