def block_tilts(res):
    """
    Median |tilt| per block of an :func:`oh_line_tilts` result.

    Generated by JXP and Claude.

    Args:
        res (`numpy.ndarray`_): Output of ``vt.oh_line_tilts``.

    Returns:
        :obj:`tuple`: blocks and their median absolute tilt (pixels).
    """
    blocks = np.unique(res[:, 0]).astype(int)
    return blocks, np.array([np.median(np.abs(res[res[:, 0] == b, 2]))
                             for b in blocks])


def fig_tilts():
    """
    OH-line tilt across the blocks with the Keck and the refined solutions
    (Hn3 and Kbb), and the repeatability of the per-lenslet shifts.

    Generated by JXP and Claude.
    """
    fig, axes = plt.subplots(2, 2, figsize=(11, 7.5))
    for row, setup in enumerate(['Hn3_100', 'Kbb_050']):
        cfg = vt.SETUPS[setup]
        sky = vt.rectified_frame(setup, cfg['sky'])
        sci = vt.rectified_frame(setup, cfg['sci'])
        keck, _ = vt.oh_line_tilts(sky['image'], sky['gpm'], sky['layout'],
                                   sky['lam'])
        shifts, msci = vt.refinement_shifts(sci, cfg['lamps'])
        _, msky = vt.refinement_shifts(sky, cfg['lamps'])
        ref, _ = vt.oh_line_tilts(sky['image'], sky['gpm'], sky['layout'],
                                  vt.refined_wavelengths(sky['lam'], shifts))
        vt.tilt_summary(keck, f'{setup} Keck')
        vt.tilt_summary(ref, f'{setup} refined')
        ax = axes[row, 0]
        for res, col, lab in [(keck, ORANGE, 'Keck coefficients'),
                              (ref, BLUE, f'refined on {cfg["sci"]}')]:
            b, t = block_tilts(res)
            ax.plot(b, t, 'o-', color=col, ms=3, lw=1,
                    label=f'{lab}: median {np.median(np.abs(res[:, 2])):.3f}')
        ax.axhline(vt.TILT_MAX, color=INK2, ls='--', lw=0.8)
        ax.set_ylabel('median |tilt| over 64 lenslets (px)')
        ax.set_xlabel('block (Keck lenslet column)')
        ax.set_title(f'{setup}: OH tilt test on {cfg["sky"]}', fontsize=9)
        ax.legend(fontsize=7)
        ax = axes[row, 1]
        ok = np.isfinite(msci) & np.isfinite(msky)
        ax.plot(msci[ok], msky[ok], '.', ms=2, color=INK)
        lim = np.percentile(np.r_[msci[ok], msky[ok]], [0.5, 99.5])
        ax.plot(lim, lim, color=ORANGE, lw=0.8)
        ax.set_xlabel(f'shift on {cfg["sci"]} (px)')
        ax.set_ylabel(f'shift on {cfg["sky"]} (px)')
        ax.set_title(f'{setup}: per-lenslet OH shifts, r = '
                     f'{np.corrcoef(msci[ok], msky[ok])[0, 1]:.3f}, '
                     f'std(diff) = {np.std(msci[ok] - msky[ok]):.3f} px',
                     fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / 'm4_oh_tilts.png', dpi=100)
    plt.close(fig)


def fig_tiltmodel():
    """
    Residuals of the Keck-derived tilts against the per-lenslet Keck
    solutions (Kbb 2024, Hn3 2016).

    Generated by JXP and Claude.
    """
    from pypeit import slittrace
    spec = load_spectrograph('keck_osiris')
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    for ax, (filt, mjd, dtmp7) in zip(axes, [('Kbb', 60343.494, 54.24),
                                              ('Hn3', 57468.443, 55.34)]):
        hdr = fits.Header({'SFILTER': filt, 'MJD-OBS': mjd, 'DTMP7': dtmp7,
                           'SSCALE': '0.050'})
        spec.set_lenslet_state(filt, mjd)
        lay = spec.lenslet_layout()
        left, right = spec.get_block_slit_edges(
            np.zeros((2048, lay.meta['nspat'])), 1)
        slits = slittrace.SlitTraceSet(left, right, 'Fiber', nspec=2048,
                                       nspat=lay.meta['nspat'],
                                       PYP_SPEC=spec.name)
        par = spec.default_pypeit_par()['calibrations']['wavelengths']
        wv = spec.get_fixed_wavecalib(slits, hdr, par)
        tilts = spec.get_fixed_tilts(slits, raw_header=hdr)
        waveimg = wv.build_waveimg(tilts.fit2tiltimg(slits.slit_img()), slits)
        lam = spec.lenslet_wavelengths(spec.frame_expansion(hdr))
        band = lr.lenslet_band_mask(lam, lay)[:, ::-1]
        exact = lam[:, ::-1] * 10.
        model = waveimg[:, np.asarray(lay['pos'])].T
        d = ((model - exact) / np.abs(np.gradient(exact, axis=1)))[band]
        rms = np.sqrt(np.mean(d**2))
        mad = 1.4826 * np.median(np.abs(d))
        print(f'{filt}: tilt-model residual rms {rms:.4f} px, robust '
              f'{mad:.4f} px, p99 {np.percentile(np.abs(d), 99):.3f} px, '
              f'max {np.max(np.abs(d)):.2f} px')
        ax.hist(d, bins=np.linspace(-0.2, 0.2, 81), color=BLUE,
                histtype='stepfilled', alpha=0.7)
        ax.set_yscale('log')
        ax.set_xlabel('wave(tilts) - Keck per-lenslet solution (px)')
        ax.set_title(f'{filt}: rms {rms:.3f} px (robust {mad:.3f} px)',
                     fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / 'm4_tilt_model.png', dpi=100)
    plt.close(fig)


def line_residuals(wave, resid, sky, gpm, lines, halfwidth=3):
    """
    Integrated residual of each OH line relative to its sky flux, pooled
    over all lenslets.

    Generated by JXP and Claude.

    Args:
        wave, resid, sky, gpm (`numpy.ndarray`_): (nspec, nfib) arrays.
        lines (`numpy.ndarray`_): Line wavelengths.
        halfwidth (:obj:`int`, optional): Half width of the window (px).

    Returns:
        `numpy.ndarray`_: Fractional residual of each line (NaN if absent).
    """
    xline = sky - skysub.running_median(sky, gpm, 41)
    y = resid - skysub.running_median(resid, gpm, 41)
    pix = np.arange(wave.shape[0])
    out = []
    for wl in lines:
        sx = sy = 0.
        for k in range(wave.shape[1]):
            if not (wave[0, k] < wl < wave[-1, k]):
                continue
            p = int(round(np.interp(wl, wave[:, k], pix)))
            sl = slice(max(p - halfwidth, 0), p + halfwidth + 1)
            g = gpm[sl, k]
            # Ignore windows with masked pixels or cosmic rays in the sky
            if not np.all(g) or np.any(np.abs(y[sl, k])
                                       > 0.5 * np.abs(xline[sl, k]) + 200):
                continue
            sx += xline[sl, k].sum()
            sy += y[sl, k].sum()
        out.append(sy / sx if sx > 0 else np.nan)
    return np.array(out)


def pair_sky(redux, raw):
    """
    Background (sky) frame of a science frame in the dev-suite pypeit file.

    Generated by JXP and Claude.

    Args:
        redux (`Path`_): Reduction directory (holds the pypeit file).
        raw (:obj:`str`): Raw file name of the science frame.

    Returns:
        :obj:`str`: Raw file name of its background frame.
    """
    tbl = PypeItFile.from_file(
        str(next(Path(redux).glob('*.pypeit')))).data
    names = list(tbl['filename'])
    bkg = int(tbl['bkg_id'][names.index(raw)])
    return names[list(tbl['comb_id']).index(bkg)]


def fig_ohscale(redux):
    """
    Davies OH scaling: per-line residuals of a sky-sky pair before and
    after the scaling, and the OH-line residuals of the NGC 3245 A-B frames
    with and without the scaling model.

    Generated by JXP and Claude.

    Args:
        redux (`Path`_): Kbb reduction directory.
    """
    a = vt.rectified_frame('Kbb_050', 'OS.20240203.43383.79.fits')
    b = vt.rectified_frame('Kbb_050', 'OS.20240203.45436.78.fits')
    pos = np.asarray(a['layout']['pos'])
    fa, fb = a['image'][:, pos], b['image'][:, pos]
    gpm = a['gpm'][:, pos] & b['gpm'][:, pos]
    wave = a['lam'].T
    resid = fa - fb
    ivar = np.where(gpm, 1. / (np.abs(fa) + np.abs(fb) + 2 * 8.**2), 0.)
    model, scales, npix, _, stats = skysub.oh_scaled_sky(
        wave, resid, ivar, fb, gpm, np.zeros(pos.size, dtype=int))
    ll = waveio.load_line_lists(['OH_OSIRIS'])[1]
    lw = wvutils.isolated_lines(ll['wave'], 15.,
                                line_ok=np.asarray(ll['NIST']) > 0)
    before = line_residuals(wave, resid, fb, gpm, lw)
    after = line_residuals(wave, resid - model, fb, gpm, lw)
    names = skysub.OH_GROUP_NAMES
    fit = {names[g]: round(float(scales[0, g]), 4)
           for g in range(len(names)) if npix[0, g] > 0}
    print(f'sky-sky (43383 - 45436): r - 1 = {fit}; per-line residual: '
          f'median |before| {np.nanmedian(np.abs(before)):.4f}, median '
          f'|after| {np.nanmedian(np.abs(after)):.4f}; line-pixel rms '
          f'{stats["line_rms_before"]:.1f} -> {stats["line_rms_after"]:.1f} '
          f'(line-free {stats["cont_rms"]:.1f})')

    # NGC 3245 A-B frames (spec2d; the lenslet image has one spectral
    # column per lenslet): integrated OH-line residual relative to the sky
    # line flux of the B frame, without (SCIIMG) and with (SCIIMG -
    # SKYMODEL) the Davies model.  The spec1d sky columns hold the sky of
    # the un-subtracted frame (zero here), so the spec2d is used.
    rows = []
    sky_cache = {}
    for f in sorted((redux / 'Science').glob('spec2d_*NGC3245*.fits')):
        with fits.open(f) as hdu:
            hdr = hdu[0].header
            sci = hdu['DET01-SCIIMG'].data
            model = hdu['DET01-SKYMODEL'].data
            wimg = hdu['DET01-WAVEIMG'].data
            bpm = hdu['DET01-BPMMASK'].data
        braw = pair_sky(redux, hdr['FILENAME'])
        if braw not in sky_cache:
            sky_cache[braw] = vt.rectified_frame('Kbb_050', braw)
        bfr = sky_cache[braw]
        pos = np.asarray(bfr['layout']['pos'])
        w = wimg[:, pos]
        g = (bpm[:, pos] == 0) & bfr['gpm'][:, pos] & (w > 0)
        sk = bfr['image'][:, pos]
        r0 = line_residuals(w, sci[:, pos], sk, g, lw)
        r1 = line_residuals(w, sci[:, pos] - model[:, pos], sk, g, lw)
        rows.append((hdr['FILENAME'][3:20], hdr['EXPTIME'],
                     np.nanmedian(np.abs(r0)), np.nanmedian(np.abs(r1))))
    for r in rows:
        print(f'{r[0]} ({r[1]:.0f} s): median |OH-line residual| / sky '
              f'{r[2]:.4f} (A-B) -> {r[3]:.4f} (A-B-Davies)')
    if len(rows) > 0:
        b_ = np.array([r[2] for r in rows])
        a_ = np.array([r[3] for r in rows])
        print(f'NGC 3245 ({len(rows)} frames): median {np.median(b_):.4f} '
              f'-> {np.median(a_):.4f}; improved in '
              f'{np.sum(a_ < b_)}/{len(rows)} frames')

    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    ax = axes[0]
    ax.plot(lw, before, 'o', color=ORANGE, ms=4, label='A - B')
    ax.plot(lw, after, 'o', color=BLUE, ms=4, label='A - B - Davies model')
    ax.axhline(0, color=INK2, lw=0.8)
    for e in skysub.OH_GROUP_EDGES:
        if BAND[0] < e < BAND[1]:
            ax.axvline(e, color=INK2, ls=':', lw=0.8)
    ax.set_xlabel('OH line (vacuum A)')
    ax.set_ylabel('integrated residual / sky line flux')
    ax.set_title('Sky - sky pair (OS.20240203.43383 - .45436)', fontsize=9)
    ax.legend(fontsize=8)
    ax = axes[1]
    if len(rows) > 0:
        x = np.arange(len(rows))
        ax.plot(x, b_, 'o-', color=ORANGE, label='A - B')
        ax.plot(x, a_, 'o-', color=BLUE, label='A - B - Davies model')
        ax.set_xticks(x)
        ax.set_xticklabels([r[0][9:] for r in rows], rotation=90,
                           fontsize=6)
        ax.set_xlabel('NGC 3245 exposure')
        ax.set_ylabel('median |line residual| / sky line flux')
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(HERE / 'm4_oh_scaling.png', dpi=100)
    plt.close(fig)


def stack_lenslets(files, wave_grid):
    """
    Inverse-variance mean of the lenslet spectra of several spec1d files
    on a common wavelength grid.

    Generated by JXP and Claude.

    Args:
        files (:obj:`list`): spec1d files.
        wave_grid (`numpy.ndarray`_): Output wavelengths.

    Returns:
        :obj:`tuple`: lenslet ids, flux (nlens, nwave), ivar.
    """
    num, den = {}, {}
    for f in files:
        for s in SpecObjs.from_fitsfile(f, chk_version=False):
            g = s.BOX_MASK & (s.BOX_COUNTS_IVAR > 0)
            if np.sum(g) < 100:
                continue
            k = int(s.MASKDEF_ID)
            fl = np.interp(wave_grid, s.BOX_WAVE[g], s.BOX_COUNTS[g],
                           left=np.nan, right=np.nan)
            iv = np.interp(wave_grid, s.BOX_WAVE[g], s.BOX_COUNTS_IVAR[g],
                           left=0., right=0.)
            ok = np.isfinite(fl)
            num.setdefault(k, np.zeros(wave_grid.size))
            den.setdefault(k, np.zeros(wave_grid.size))
            num[k][ok] += (fl * iv)[ok]
            den[k][ok] += iv[ok]
    ids = np.array(sorted(num))
    den_a = np.array([den[k] for k in ids])
    flux = np.array([num[k] for k in ids]) / np.where(den_a > 0, den_a, 1.)
    return ids, flux, den_a


def fig_ngc(redux):
    """
    NGC 3245: continuum image, emission/absorption-line maps and the
    nuclear spectrum from the stack of the 600-s exposures.

    Generated by JXP and Claude.

    Args:
        redux (`Path`_): Kbb reduction directory.
    """
    files = [f for f in sorted((redux / 'Science').glob(
        'spec1d_*NGC3245*.fits')) if fits.getheader(f)['EXPTIME'] > 100]
    grid = np.arange(BAND[0], BAND[1], 2.5)
    ids, flux, ivar = stack_lenslets(files, grid)
    crow, ccol = np.divmod(ids, 51)
    img = np.full((66, 51), np.nan)

    def to_img(vals):
        out = img.copy()
        out[65 - crow, ccol] = vals     # Keck I row flip (DRP cube)
        return out[:, 16:35]

    def band_mean(lo, hi):
        sel = (grid > lo) & (grid < hi)
        return np.nanmean(flux[:, sel], axis=1)

    cont = band_mean(20800., 21200.) + band_mean(22000., 22300.)
    cimg = to_img(cont / 2.)
    # Nuclear spectrum: 3x3 lenslets around the continuum peak
    k0 = int(np.nanargmax(cont))
    near = (np.abs(crow - crow[k0]) <= 1) & (np.abs(ccol - ccol[k0]) <= 1)
    nuc = np.nanmean(flux[near], axis=0)
    norm = nuc / np.nanmedian(nuc[(grid > 21000) & (grid < 22000)])
    # Lines: H2 1-0 S(1) and Br gamma in emission, CO 2-0 bandhead
    lines = {'H2 1-0 S(1)': 21218.3, 'Br gamma': 21661.2,
             'H2 1-0 S(0)': 22235.3, 'H2 1-0 S(2)': 20338.0,
             'CO 2-0': 22935.}

    def line_map(lw, width=8., off=(25., 45.)):
        lo = lw * (1 + Z_NGC3245)
        on = (grid > lo - width) & (grid < lo + width)
        side = ((grid > lo - off[1]) & (grid < lo - off[0])) \
            | ((grid > lo + off[0]) & (grid < lo + off[1]))
        c = np.nanmedian(flux[:, side], axis=1)
        return np.nansum(flux[:, on] - c[:, None], axis=1) * 2.5, c

    h2, h2c = line_map(lines['H2 1-0 S(1)'])
    brg, _ = line_map(lines['Br gamma'])
    # CO bandhead depth (absorption-line index)
    co_in = band_mean(23050., 23200.)
    co_out = band_mean(22800., 22950.)
    co = 1. - co_in / co_out
    for nm in ['H2 1-0 S(1)', 'Br gamma']:
        lo = lines[nm] * (1 + Z_NGC3245)
        sel = np.abs(grid - lo) < 8.
        side = (np.abs(grid - lo) > 25.) & (np.abs(grid - lo) < 45.)
        ew = np.nansum(norm[sel] - np.nanmedian(norm[side])) * 2.5
        print(f'Nuclear {nm} at {lo:.1f} A: equivalent width {ew:+.2f} A')
    tot = np.nansum(h2[near])
    noise = np.nanstd(h2) * np.sqrt(near.sum())
    print(f'H2 S(1) flux in the 3x3 nucleus {tot:.0f} counts, map noise '
          f'{noise:.0f}; CO index nucleus {np.nanmean(co[near]):.3f}, '
          f'median {np.nanmedian(co):.3f}')
    print(f'Continuum peak at lenslet {ids[k0]} (row {crow[k0]}, col '
          f'{ccol[k0]}); {len(files)} exposures stacked')

    fig = plt.figure(figsize=(13, 7.5))
    gs = fig.add_gridspec(2, 4, height_ratios=[1.3, 1])
    ext = [15.5, 34.5, -0.5, 65.5]
    for i, (dat, title, cmap) in enumerate([
            (np.log10(np.clip(cimg, np.nanpercentile(cimg, 1), None)),
             'K continuum (log)', 'viridis'),
            (to_img(h2), 'H2 1-0 S(1) (continuum-subtracted)', 'magma'),
            (to_img(brg), 'Br gamma (continuum-subtracted)', 'magma'),
            (to_img(co), 'CO 2-0 bandhead depth', 'cividis')]):
        ax = fig.add_subplot(gs[0, i])
        vmin, vmax = np.nanpercentile(dat, [2, 99.5])
        im = ax.imshow(dat, origin='lower', cmap=cmap, vmin=vmin, vmax=vmax,
                       extent=ext, aspect='equal')
        ax.set_title(title, fontsize=9)
        ax.set_xlabel('lenslet column')
        if i == 0:
            ax.set_ylabel('lenslet row (flipped)')
        fig.colorbar(im, ax=ax, fraction=0.05)
    ax = fig.add_subplot(gs[1, :])
    ax.plot(grid, norm, color=INK, lw=0.6)
    for nm, lw in lines.items():
        x = lw * (1 + Z_NGC3245)
        ax.axvline(x, color=ORANGE, lw=0.6, ls='--')
        ax.text(x, 1.12, nm, rotation=90, fontsize=7, va='bottom')
    ax.set_xlim(*BAND)
    ax.set_ylim(0.5, 1.3)
    ax.set_xlabel('vacuum wavelength (A)')
    ax.set_ylabel('nuclear spectrum (normalised)')
    ax.set_title(f'NGC 3245 nucleus (3x3 lenslets, {len(files)} x 600 s, '
                 'not telluric corrected)', fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / 'm4_ngc3245.png', dpi=100)
    plt.close(fig)


def fig_telluric(redux):
    """
    Telluric-corrected A0V standard divided by its stellar model.

    Generated by JXP and Claude.

    Args:
        redux (`Path`_): Kbb reduction directory.
    """
    f = sorted(redux.glob('*HD101060*_ps_tellcorr.fits'))[0]
    t = fits.getdata(f, 'SPECTRUM')
    w, fl, m = t['wave'], t['flux'], t['mask'].astype(bool)
    tel, om = t['telluric'], t['obj_model']
    g = m & (tel > 0.5) & (om > 0) & (w > BAND[0]) & (w < BAND[1])
    r = fl[g] / om[g]
    edges = np.arange(BAND[0], BAND[1], 50.)
    cen, binned = [], []
    for lo in edges:
        sel = (w[g] >= lo) & (w[g] < lo + 50)
        if np.sum(sel) > 5:
            cen.append(lo + 25)
            binned.append(np.median(r[sel]))
    cen, binned = np.array(cen), np.array(binned)
    print(f'{f.name}: pixel rms {np.std(r - 1):.3f}; 50-A binned rms '
          f'{np.std(binned - 1):.3f}, median |dev| '
          f'{np.median(np.abs(binned - 1)):.3f}, max |dev| '
          f'{np.max(np.abs(binned - 1)):.3f}')
    fig, axes = plt.subplots(2, 1, figsize=(11, 6.5), sharex=True)
    ax = axes[0]
    obs = fl * tel
    ax.plot(w[m], obs[m], color=INK2, lw=0.5, label='observed (counts)')
    ax.plot(w[m], fl[m], color=BLUE, lw=0.6, label='telluric corrected')
    ax.plot(w, om, color=ORANGE, lw=1, label='A0V model x response')
    ax.set_ylim(0, 1.3 * np.nanpercentile(fl[g], 99))
    ax.legend(fontsize=8)
    ax.set_title(f'HD101060 (A0V): {f.name}', fontsize=9)
    ax = axes[1]
    ax.plot(w[g], r, '.', color=INK2, ms=1.5)
    ax.plot(cen, binned, 'o-', color=BLUE, ms=3,
            label=f'50 A bins: rms {np.std(binned - 1):.3f}')
    ax.axhline(1, color=ORANGE)
    ax.set_ylim(0.85, 1.15)
    ax.set_xlim(*BAND)
    ax.set_xlabel('vacuum wavelength (A)')
    ax.set_ylabel('corrected / model')
    ax.legend(fontsize=8)
