"""
Figures for Report 04 (M2, lenslet rectification vs the DRP cube).

Usage:  PYPEIT_DEV=<dev suite> python make_m2_figures.py <scratch_dir>

Re-uses the helpers of ``vet_tests/test_keck_osiris_rectify.py``; the
rectified frames are written to ``<scratch_dir>``, the PNG files next to
this script.

Generated by JXP and Claude.
"""
import sys
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use('Agg')
from matplotlib import pyplot as plt
from astropy.io import fits

from pypeit.core import lenslet_rectify as lr
from pypeit.scripts.osiris_rectify import OsirisRectify
from pypeit.spectrographs.util import load_spectrograph

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[3] / 'vet_tests'))
import test_keck_osiris_rectify as vt  # noqa: E402

BLUE, ORANGE, AQUA = '#2a78d6', '#eb6834', '#1baf7a'
INK, INK2 = '#0b0b0b', '#52514e'


def main(scratch):
    """
    Build all M2 figures.

    Generated by JXP and Claude.

    Args:
        scratch (`Path`_): Directory for the rectified frames.
    """
    scratch.mkdir(parents=True, exist_ok=True)
    spec = load_spectrograph('keck_osiris')
    hdr = fits.getheader(vt.FRAME_A)
    coeffs = spec.load_wave_coeffs(hdr['MJD-OBS'])
    matrix = lr.RectMatrix.from_file(vt.MATRIX)
    t = spec.exptime_from_header(hdr)
    ref = fits.getdata(vt.REF, 0).astype(float)
    refgpm = fits.getdata(vt.REF, 2) == 9
    rect, cubes = {}, {}
    for method in ['drp', 'lstsq']:
        f = scratch / f'hn3_{method}.fits'
        OsirisRectify.main(OsirisRectify.parse_args(
            [str(vt.FRAME_A), '--bkg', str(vt.FRAME_B), '-m', str(vt.MATRIX),
             '--method', method, '-o', str(f), '--overwrite']))
        with fits.open(f) as hdu:
            rect[method] = (hdu['RECT'].data / t, hdu['IVAR'].data * t**2,
                            hdu['MASK'].data.astype(bool))
        cubes[method] = vt.to_cube(rect[method][0], rect[method][2], matrix,
                                   hdr, coeffs)
    # S/N from the lstsq variance
    iv = rect['lstsq'][1]
    var = np.where(iv > 0, 1 / np.where(iv > 0, iv, 1), 0)
    vcube, _ = vt.to_cube(var, rect['lstsq'][2], matrix, hdr, coeffs)
    g = cubes['lstsq'][1] & refgpm
    snr = np.where(g, ref, 0).sum(2) / np.sqrt(np.where(g, vcube, 0).sum(2)
                                               + 1e-30)
    # DRP emulation
    a = fits.getdata(vt.FRAME_A, 0).astype(np.float32)
    b = fits.getdata(vt.FRAME_B, 0).astype(np.float32)
    img, crm = vt.drp_cosmic_mask_2016(lr.subtract_reference_rows(a - b))
    remu, _, _ = lr.rectify_drp(img, crm, matrix)
    cubes['emu'] = vt.to_cube(remu, vt.drp_c_quality_bpm(matrix, crm),
                              matrix, hdr, coeffs)

    flux = {k: vt.spaxel_fluxes(*cubes[k], ref, refgpm) for k in cubes}
    sel = snr > vt.SNR_MIN

    # --- Figure 1: white-light images and fractional differences
    fig, axes = plt.subplots(2, 3, figsize=(11, 8.2), layout='constrained')
    f0 = flux['drp'][1]
    im = axes[0, 0].imshow(np.log10(np.clip(f0.T, 1, None)), origin='lower',
                           cmap='Greys_r')
    axes[0, 0].set_title('DRP reference: log10 white light')
    fig.colorbar(im, ax=axes[0, 0], shrink=0.8)
    panels = [((0, 1), 'drp', 'drp (PypeIt input) / DRP - 1', 0.05),
              ((0, 2), 'lstsq', 'lstsq (PypeIt input) / DRP - 1', 0.05),
              ((1, 0), 'emu', 'drp (DRP-emulated input) / DRP - 1', 1e-4)]
    for (i, j), key, title, vmax in panels:
        f1, fr = flux[key]
        d = np.where(sel, f1 / np.where(fr != 0, fr, 1) - 1, np.nan)
        im = axes[i, j].imshow(d.T, origin='lower', cmap='RdBu_r',
                               vmin=-vmax, vmax=vmax)
        axes[i, j].set_title(title)
        fig.colorbar(im, ax=axes[i, j], shrink=0.8)
    fd, fl = flux['drp'][0], flux['lstsq'][0]
    d = np.where(sel, fl / np.where(fd != 0, fd, 1) - 1, np.nan)
    im = axes[1, 1].imshow(d.T, origin='lower', cmap='RdBu_r', vmin=-0.05,
                           vmax=0.05)
    axes[1, 1].set_title('lstsq / drp - 1')
    fig.colorbar(im, ax=axes[1, 1], shrink=0.8)
    # Voxel difference map of the emulation at the quasar wavelength peak
    dv = (cubes['emu'][0] - ref).max(axis=2)
    im = axes[1, 2].imshow(dv.T, origin='lower', cmap='RdBu_r',
                           vmin=-0.01, vmax=0.01)
    axes[1, 2].set_title('DRP-emulated: max voxel diff (ADU/s)')
    fig.colorbar(im, ax=axes[1, 2], shrink=0.8)
    for ax in axes.flat:
        ax.set_xlabel('lenslet column')
        ax.set_ylabel('lenslet row (flipped)')
    fig.suptitle('Hn3/100 3C 273 (A-B): spaxel fluxes vs the DRP cube '
                 f'(spaxels with S/N > {vt.SNR_MIN:.0f}; grey = excluded)')
    fig.savefig(HERE / 'm2_difference_images.png', dpi=110)
    plt.close(fig)

    # --- Figure 2: per-lenslet comparison
    fig, axes = plt.subplots(2, 1, figsize=(9, 7.5), layout='constrained')
    tbl = lr.narrowband_split('Hn3')
    for key, col, lab in [('drp', BLUE, 'drp'), ('lstsq', ORANGE, 'lstsq')]:
        f1, fr = flux[key]
        ratio = f1 / np.where(fr != 0, fr, 1)
        # Lenslet id = cube row * 51 + column (DRP cube order)
        cc, rr = np.where(sel)
        axes[0].plot(rr * 51 + cc, ratio[sel], '.', ms=3, color=col,
                     label=f'{lab} (median |r-1| = '
                           f'{np.median(np.abs(ratio[sel] - 1)):.4f})')
        axes[1].semilogx(snr[sel], ratio[sel], '.', ms=3, color=col,
                         label=lab)
    for ax in axes:
        ax.axhline(1, color=INK2, lw=1)
        ax.set_ylim(0.8, 1.2)
        ax.set_ylabel('spaxel flux / DRP')
        ax.legend(loc='upper right', frameon=False)
    axes[0].set_xlabel('lenslet index (row x 51 + column, DRP cube)')
    axes[1].set_xlabel('spaxel S/N (PypeIt noise model)')
    axes[1].axvline(snr[vt.QUASAR], color=INK2, ls=':', lw=1)
    axes[1].text(snr[vt.QUASAR], 1.15, ' quasar', color=INK2)
    fig.suptitle('Per-lenslet comparison with the DRP reference cube')
    fig.savefig(HERE / 'm2_per_lenslet.png', dpi=110)
    plt.close(fig)

    # --- Figure 3: quasar spectrum
    wave, _ = lr.drp_wavelength_grid('Hn3')
    fig, axes = plt.subplots(2, 1, figsize=(9, 6), sharex=True,
                             layout='constrained',
                             gridspec_kw=dict(height_ratios=[2, 1]))
    q = vt.QUASAR
    axes[0].plot(wave, ref[q], color=INK, lw=2, label='DRP reference')
    for key, col in [('drp', BLUE), ('lstsq', ORANGE)]:
        axes[0].plot(wave, cubes[key][0][q], color=col, lw=1, label=key)
        axes[1].plot(wave, cubes[key][0][q] / ref[q], color=col, lw=1,
                     label=key)
    axes[1].plot(wave, cubes['emu'][0][q] / ref[q], color=AQUA, lw=1,
                 label='drp, DRP-emulated input')
    axes[0].set_ylabel('ADU/s')
    axes[1].set_ylabel('ratio to DRP')
    axes[1].set_ylim(0.9, 1.1)
    axes[1].axhline(1, color=INK2, lw=1)
    axes[1].set_xlabel('vacuum wavelength (nm)')
    axes[0].legend(frameon=False)
    axes[1].legend(frameon=False, ncol=3)
    axes[0].set_title(f'Quasar spaxel {q}')
    fig.savefig(HERE / 'm2_quasar_spectrum.png', dpi=110)
    plt.close(fig)

    # --- Figure 4: rectified frames (raw column order), quasar region
    s = int(tbl['slice'][(tbl['col'] == q[0]) & (tbl['row'] == 65 - q[1])][0])
    lo, hi = max(0, s - 40), s + 40
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5), layout='constrained')
    im = axes[0].imshow(rect['drp'][0][:, lo:hi].T, aspect='auto',
                        origin='lower', cmap='Greys_r', vmin=-0.5, vmax=5,
                        extent=[0, 2048, lo, hi])
    axes[0].set_title('drp rectified frame (ADU/s)')
    fig.colorbar(im, ax=axes[0])
    d = rect['lstsq'][0] - rect['drp'][0]
    im = axes[1].imshow(d[:, lo:hi].T, aspect='auto', origin='lower',
                        cmap='RdBu_r', vmin=-0.5, vmax=0.5,
                        extent=[0, 2048, lo, hi])
    axes[1].set_title('lstsq - drp (ADU/s)')
    fig.colorbar(im, ax=axes[1])
    for ax in axes:
        ax.set_xlabel('raw detector column')
        ax.set_ylabel('slice')
    fig.savefig(HERE / 'm2_rectified_frames.png', dpi=110)
    plt.close(fig)


if __name__ == '__main__':
    main(Path(sys.argv[1]))
