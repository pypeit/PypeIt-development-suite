"""
Figures for Report 05 (M3, PypeIt flow on the Hn3/100 pair).

Usage:  PYPEIT_DEV=<dev suite> python make_m3_figures.py <redux_dir>

``<redux_dir>`` is the ``run_pypeit`` output directory of
``keck_osiris_hn3_100.pypeit`` (holding ``Science/spec1d_*.fits`` and
``spec2d_*.fits``).  Re-uses the helpers of
``vet_tests/test_keck_osiris_flow.py``; the PNG files are written next to
this script.

Generated by JXP and Claude.
"""
import sys
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use('Agg')
from matplotlib import pyplot as plt
from astropy.io import fits

from pypeit import spec2dobj
from pypeit.core import lenslet_rectify as lr
from pypeit.images import rawimage
from pypeit.specobjs import SpecObjs
from pypeit.spectrographs.util import load_spectrograph

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[3] / 'vet_tests'))
import test_keck_osiris_flow as vt  # noqa: E402

BLUE, ORANGE, AQUA = '#2a78d6', '#eb6834', '#1baf7a'
INK, INK2 = '#0b0b0b', '#52514e'


def sky_frame():
    """
    Rectified sky frame (same as the vet-test fixture).

    Generated by JXP and Claude.

    Returns:
        :obj:`dict`: image, gpm, layout and Keck wavelengths (Angstrom).
    """
    spec = load_spectrograph('keck_osiris')
    par = spec.default_pypeit_par()
    par['calibrations']['osiris_rectmat_dir'] = str(vt.RAW / 'calib')
    spec.set_runtime_par(par)
    img = rawimage.RawImage(str(vt.SKY), spec, 1).process(
        par['scienceframe']['process'])
    hdr = fits.getheader(vt.SKY)
    lam = spec.lenslet_wavelengths(spec.frame_expansion(hdr))[:, ::-1] * 10.
    return dict(image=img.image, gpm=img.select_flag(invert=True),
                layout=spec.lenslet_layout(), lam=lam)


def fig_tilts(sky):
    """
    OH-line residuals versus lenslet row and the tilt per block.

    Generated by JXP and Claude.

    Args:
        sky (:obj:`dict`): Output of :func:`sky_frame`.
    """
    res, qa = vt.oh_line_tilts(sky['image'], sky['gpm'], sky['layout'],
                               sky['lam'])
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.3))
    for ax, blk, col in zip([axes[0]] * 3, [8, 26, 44],
                            [BLUE, ORANGE, AQUA]):
        sel = [q for q in qa if q[0] == blk]
        for k, (b, wl, rows, rr) in enumerate(sel):
            ax.plot(rows, rr, 'o', ms=2.5, color=col, alpha=0.5,
                    label=f'block {blk} (Keck column {blk})' if k == 0
                    else None)
            p = np.polyfit(rows, rr, 1)
            ax.plot([0, 63], np.polyval(p, [0, 63]), '-', lw=1, color=col,
                    alpha=0.6)
    axes[0].set_ylim(-0.6, 0.6)
    axes[0].set_xlabel('lenslet row within block')
    axes[0].set_ylabel('OH centroid - Keck prediction (px)')
    axes[0].legend(frameon=False, fontsize=8)
    axes[0].set_title('Residuals for every bright OH line', fontsize=10)
    blocks = np.unique(res[:, 0]).astype(int)
    med = [np.median(res[res[:, 0] == b, 2]) for b in blocks]
    axes[1].plot(res[:, 0], res[:, 2], '.', color=INK2, ms=3, alpha=0.4,
                 label='one OH line')
    axes[1].plot(blocks, med, 'o-', color=BLUE, ms=4, lw=1.5,
                 label='median per block')
    axes[1].axhspan(-vt.TILT_MAX, vt.TILT_MAX, color=AQUA, alpha=0.15,
                    label='+/-0.05 px target')
    axes[1].set_ylim(-0.6, 0.6)
    axes[1].set_xlabel('block = Keck lenslet column')
    axes[1].set_ylabel('fitted tilt over 64 lenslets (px)')
    axes[1].legend(frameon=False, fontsize=8)
    axes[1].set_title('Tilt per block (sky frame 011)', fontsize=10)
    axes[2].hist(res[:, 4], bins=40, range=(0, 0.3), color=BLUE)
    axes[2].axvline(vt.SCATTER_MAX, color=ORANGE, lw=1.5,
                    label='0.1 px target')
    axes[2].set_xlabel('per-lenslet scatter about the fit (px)')
    axes[2].set_ylabel('number of (block, line)')
    axes[2].legend(frameon=False, fontsize=8)
    axes[2].set_title(f'median {np.median(res[:, 4]):.3f} px', fontsize=10)
    fig.tight_layout()
    fig.savefig(HERE / 'm3_oh_tilts.png', dpi=110)
    plt.close(fig)


def fig_quasar(spec1d):
    """
    Collapsed images of 3C 273 (spec1d vs DRP) and its spectrum.

    Generated by JXP and Claude.

    Args:
        spec1d (`Path`_): spec1d file.
    """
    sobjs = SpecObjs.from_fitsfile(spec1d, chk_version=False)
    hdr0 = fits.getheader(spec1d)
    img = np.zeros((66, 51))
    qso = None
    for s in sobjs:
        crow, ccol = divmod(int(s.MASKDEF_ID), 51)
        g = s.BOX_MASK & (s.BOX_WAVE > vt.BAND[0]) & (s.BOX_WAVE < vt.BAND[1])
        img[crow, ccol] = np.sum(s.BOX_COUNTS[g])
        if (65 - crow, ccol) == vt.QUASAR:
            qso = s
    img = img[::-1]
    with fits.open(vt.REF) as hdu:
        cube = hdu[0].data.astype(float)
        gpm = hdu[2].data == 9
        h = hdu[0].header
    wave = (h['CRVAL1'] + h['CDELT1'] * np.arange(cube.shape[2])) * 10.
    sel = (wave > vt.BAND[0]) & (wave < vt.BAND[1])
    dimg = np.where(gpm[..., sel], cube[..., sel], 0.).sum(axis=2).T
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))
    for ax, im, title in [(axes[0], img, 'PypeIt spec1d (boxcar sum)'),
                          (axes[1], dimg, 'DRP reference cube')]:
        ax.imshow(np.arcsinh(im / np.percentile(im[im > 0], 90)),
                  origin='lower', cmap='Greys', aspect='equal')
        r, c = np.unravel_index(np.argmax(im), im.shape)
        ax.plot(c, r, '+', color=ORANGE, ms=12, mew=1.5,
                label=f'peak (row {r}, col {c})')
        ax.set_title(title, fontsize=10)
        ax.set_xlabel('lenslet column')
        ax.set_ylabel('lenslet row (Keck I flip)')
        ax.legend(frameon=False, fontsize=8, loc='upper left')
    # Spectrum: PypeIt counts (e-) -> DRP units (ADU/s); the DRP cube uses
    # DTMP7 = 0 K for this frame, so its wavelengths are rescaled
    gain, texp = 2.15, float(hdr0['EXPTIME'])
    frac = lr.drp_grating_expansion(None)
    g = qso.BOX_MASK
    axes[2].plot(wave * frac, cube[vt.QUASAR[1], vt.QUASAR[0]], '-',
                 color=INK2, lw=1.5, label='DRP spaxel (col 23, row 30)')
    axes[2].plot(qso.BOX_WAVE[g], qso.BOX_COUNTS[g] / gain / texp, '-',
                 color=BLUE, lw=1., label=f'PypeIt lenslet {qso.MASKDEF_OBJNAME}')
    axes[2].set_xlim(*vt.BAND)
    inb = (qso.BOX_WAVE > vt.BAND[0]) & (qso.BOX_WAVE < vt.BAND[1]) & g
    yv = qso.BOX_COUNTS[inb] / gain / texp
    axes[2].set_ylim(0.9 * np.percentile(yv, 1), 1.05 * np.percentile(yv, 99))
    axes[2].set_xlabel('vacuum wavelength (A)')
    axes[2].set_ylabel('ADU / s')
    axes[2].legend(frameon=False, fontsize=8)
    axes[2].set_title('3C 273 (DRP wavelengths with its 0 K DTMP7 scale)',
                      fontsize=10)
    fig.tight_layout()
    fig.savefig(HERE / 'm3_quasar.png', dpi=110)
    plt.close(fig)


def fig_lenslet_image(spec2d):
    """
    The rectified A-B lenslet image around the quasar blocks.

    Generated by JXP and Claude.

    Args:
        spec2d (`Path`_): spec2d file.
    """
    s2d = spec2dobj.Spec2DObj.from_file(spec2d, 'DET01', chk_version=False)
    img = np.where(s2d.bpmmask.mask == 0, s2d.sciimg, np.nan)
    fig, axes = plt.subplots(1, 2, figsize=(15, 5),
                             gridspec_kw=dict(width_ratios=[2, 1]))
    vmax = np.nanpercentile(img, 99.5)
    axes[0].imshow(img.T, origin='lower', aspect='auto', cmap='Greys',
                   vmin=-0.05 * vmax, vmax=vmax)
    axes[0].set_xlabel('spectral pixel (flipped raw column)')
    axes[0].set_ylabel('spatial pixel = 64 x block + lenslet row')
    axes[0].set_title('Rectified A-B frame, all 51 blocks', fontsize=10)
    sub = img[:, 64 * 21:64 * 26]
    axes[1].imshow(sub.T, origin='lower', aspect='auto', cmap='Greys',
                   vmin=-0.05 * vmax, vmax=0.3 * vmax,
                   extent=[0, img.shape[0], 64 * 21, 64 * 26])
    axes[1].set_xlim(800, 1500)
    axes[1].set_xlabel('spectral pixel')
    axes[1].set_title('Blocks 21-25 (quasar in block 23)', fontsize=10)
    fig.tight_layout()
    fig.savefig(HERE / 'm3_lenslet_image.png', dpi=110)
    plt.close(fig)


def main(redux):
    """
    Build all M3 figures.

    Generated by JXP and Claude.

    Args:
        redux (`Path`_): run_pypeit output directory.
    """
    sci = redux / 'Science'
    fig_tilts(sky_frame())
    fig_quasar(sorted(sci.glob('spec1d_*.fits'))[0])
    fig_lenslet_image(sorted(sci.glob('spec2d_*.fits'))[0])


if __name__ == '__main__':
    main(Path(sys.argv[1]))
