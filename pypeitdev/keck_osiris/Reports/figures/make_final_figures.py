"""
Figures and numbers for the consolidated Keck/OSIRIS report
(``keck_osiris_report.md``): the Kn3/0.035" tilt-residual issue (M5 Q&A 3).

Usage::

    PYPEIT_DEV=<dev suite> python make_final_figures.py <kn3_redux> [part ...]

``<kn3_redux>`` is the ``run_pypeit`` output directory of
``keck_osiris_kn3_035.pypeit`` (``Science/spec1d_*.fits`` and
``spec2d_*.fits``).  ``part`` selects the outputs (default: all):

- ``hist``: pixel histograms of the Keck-derived tilt residual (model minus
  exact per-lenslet Keck solution) for Hn3 2016, Kbb 2024 and Kn3 2024, and
  for Kn3 2024 without the peculiar lenslets (``final_tilt_hist.png``);
- ``map``: per-lenslet rms of the residual on the Keck lenslet grid for
  Kn3 2024, the same filter with the 2016-epoch coefficients, and Kbb 2024,
  with the peculiar lenslets circled (``final_tilt_map.png``);
- ``lenslets``: residual versus spectral pixel of the worst lenslets, the
  deviation of their Keck solution from their two neighbours, and the
  per-lenslet rms with the 2016 versus the 2024 Kn3 coefficients
  (``final_tilt_lenslets.png``);
- ``redux``: the same residual measured in the Kn3 reduction, spec1d
  ``BOX_WAVE`` minus the spec2d ``WAVEIMG`` of each lenslet, against the
  prediction from the coefficients (``final_tilt_redux.png``).

All residuals are computed from the Keck wavelength coefficients shipped
with PypeIt (``pypeit/data/spectrographs/keck_osiris``) with the production
tilt model (:func:`pypeit.core.lenslet_rectify.lenslet_block_tilts`,
Legendre orders ``KeckOSIRISSpectrograph.TILT_ORDER``).  A lenslet is
"peculiar" when the rms of its residual exceeds ``PECULIAR`` (0.2 px), the
threshold of Report 07.  The PNG files are written next to this script with
a ``final_`` prefix; the numbers quoted in the report are printed.

Generated by JXP and Claude.
"""
import sys
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use('Agg')
from matplotlib import pyplot as plt
from matplotlib.colors import LogNorm

from pypeit import log
from pypeit import PypeItError
from pypeit.core import lenslet_rectify as lr
from pypeit.spec2dobj import AllSpec2DObj
from pypeit.specobjs import SpecObjs
from pypeit.spectrographs.util import load_spectrograph

HERE = Path(__file__).resolve().parent
BLUE, ORANGE, AQUA, PURPLE = '#2a78d6', '#eb6834', '#1baf7a', '#8a5cc2'
INK2 = '#52514e'
PECULIAR = 0.2                  # px; per-lenslet rms threshold (Report 07)

# (label, filter, MJD-OBS, lenslet scale) of the cases compared; the MJDs
# are those of the dev-suite frames (Kn3 2016 uses the Hn3 date, i.e. the
# 2016 coefficient epoch, for an epoch-to-epoch comparison of one filter)
CASES = {'Kn3 2024': ('Kn3', 60535.53, 0.035),
         'Kn3 2016 coeffs': ('Kn3', 57468.44, 0.035),
         'Hn3 2016': ('Hn3', 57468.44, 0.100),
         'Kbb 2024': ('Kbb', 60343.49, 0.050)}


def tilt_residuals(label):
    """
    Residual of the Keck-derived tilt model for one filter and epoch.

    Generated by JXP and Claude.

    Args:
        label (:obj:`str`): Key of :data:`CASES`.

    Returns:
        :obj:`dict`: ``layout`` (lenslet table), ``lam`` (nm, raw column
        order), ``resid`` (model - exact, px, PypeIt spectral order, NaN
        outside the band), ``rms`` (per-lenslet rms, px), ``coeffs`` (name
        of the Keck coefficient file).
    """
    filt, mjd, scale = CASES[label]
    # A fresh instance per case: the layout and wavelengths are cached
    spec = load_spectrograph('keck_osiris')
    spec.set_lenslet_state(filt, mjd, scale=scale)
    lay = spec.lenslet_layout()
    # No grating-temperature term (the production default)
    lam = spec.lenslet_wavelengths(1.0)
    _, resid = lr.lenslet_block_tilts(lam, lay, order=spec.TILT_ORDER)
    good = np.isfinite(resid)
    rms = np.sqrt(np.nanmean(np.where(good, resid, np.nan)**2, axis=1))
    return dict(layout=lay, lam=lam, resid=resid, rms=rms,
                coeffs=Path(str(spec.wave_coeff_file(mjd))).name)


def summary(label, res, mask=None):
    """
    Print and return the statistics of a residual array.

    Generated by JXP and Claude.

    Args:
        label (:obj:`str`): Name printed with the numbers.
        res (:obj:`dict`): Output of :func:`tilt_residuals`.
        mask (`numpy.ndarray`_, optional): Lenslets to keep (all if None).

    Returns:
        `numpy.ndarray`_: The finite pixel residuals that were used (px).
    """
    keep = np.ones(len(res['rms']), dtype=bool) if mask is None else mask
    d = res['resid'][keep]
    d = d[np.isfinite(d)]
    rms = np.sqrt(np.mean(d**2))
    mad = 1.4826 * np.median(np.abs(d))
    print(f'{label}: {np.sum(keep)} lenslets, rms {rms:.3f} px, robust '
          f'{mad:.3f} px, p99 {np.percentile(np.abs(d), 99):.3f} px, max '
          f'{np.max(np.abs(d)):.2f} px')
    return d


def peculiar(res):
    """
    Peculiar lenslets: per-lenslet residual rms above :data:`PECULIAR`.

    Generated by JXP and Claude.

    Args:
        res (:obj:`dict`): Output of :func:`tilt_residuals`.

    Returns:
        `numpy.ndarray`_: Boolean flag per lenslet of the layout.
    """
    return np.nan_to_num(res['rms']) > PECULIAR


def fig_hist(allres):
    """
    Pixel histograms of the tilt residual (``final_tilt_hist.png``).

    Generated by JXP and Claude.

    Args:
        allres (:obj:`dict`): :func:`tilt_residuals` output per case.
    """
    fig, ax = plt.subplots(figsize=(7.5, 4.5))
    bins = np.linspace(-2.0, 2.0, 321)       # Kbb has one 4.5-px pixel
    for label, color in [('Hn3 2016', AQUA), ('Kbb 2024', PURPLE),
                         ('Kn3 2024', ORANGE)]:
        d = summary(label, allres[label])
        rms = np.sqrt(np.mean(d**2))
        ax.hist(d, bins=bins, histtype='step', color=color, lw=1.4,
                label=f'{label} (all; rms {rms:.3f} px)')
    kn3 = allres['Kn3 2024']
    bad = peculiar(kn3)
    d = summary(f'Kn3 2024 without {bad.sum()} peculiar', kn3, ~bad)
    ax.hist(d, bins=bins, histtype='step', color=BLUE, lw=1.4, ls='--',
            label=f'Kn3 2024 without the {bad.sum()} peculiar lenslets '
                  f'(rms {np.sqrt(np.mean(d**2)):.3f} px)')
    for label in ['Hn3 2016', 'Kbb 2024', 'Kn3 2016 coeffs']:
        b = peculiar(allres[label])
        summary(f'{label} without {b.sum()} peculiar', allres[label], ~b)
    ax.set_yscale('log')
    ax.set_xlabel('tilt-model wavelength - Keck per-lenslet solution (px)')
    ax.set_ylabel('pixels (in band)')
    ax.set_title('Keck-derived tilts: residual per pixel', fontsize=10)
    ax.legend(fontsize=7.5, frameon=False, loc='upper left')
    fig.tight_layout()
    fig.savefig(HERE / 'final_tilt_hist.png', dpi=110)
    plt.close(fig)


def grid_image(res):
    """
    Per-lenslet rms on the 66 x 51 Keck lenslet grid.

    Generated by JXP and Claude.

    Args:
        res (:obj:`dict`): Output of :func:`tilt_residuals`.

    Returns:
        `numpy.ndarray`_: (66, 51) image, NaN where no lenslet is used.
    """
    lay = res['layout']
    img = np.full((66, 51), np.nan)         # full Keck lenslet grid
    # crow/ccol: position on the Keck grid (MASKDEF_ID = crow * 51 + ccol)
    img[np.asarray(lay['crow']), np.asarray(lay['ccol'])] = res['rms']
    return img


def fig_map(allres):
    """
    Per-lenslet residual rms on the lenslet grid (``final_tilt_map.png``).

    Generated by JXP and Claude.

    Args:
        allres (:obj:`dict`): :func:`tilt_residuals` output per case.
    """
    labels = ['Kn3 2024', 'Kn3 2016 coeffs', 'Kbb 2024']
    fig, axes = plt.subplots(1, 3, figsize=(14, 5.6))
    norm = LogNorm(vmin=0.01, vmax=1.0)
    for ax, label in zip(axes, labels):
        res = allres[label]
        im = ax.imshow(grid_image(res), origin='lower', cmap='viridis',
                       norm=norm, aspect='auto')
        lay = res['layout']
        bad = peculiar(res)
        ax.scatter(np.asarray(lay['ccol'])[bad],
                   np.asarray(lay['crow'])[bad],
                   s=60, facecolors='none', edgecolors=ORANGE, lw=1.2)
        ax.set_xlabel('Keck lenslet column')
        ax.set_ylabel('Keck lenslet row (raw, not flipped)')
        ax.set_title(f'{label}: {res["coeffs"]}\n{bad.sum()} lenslets '
                     f'> {PECULIAR} px rms (circled)', fontsize=8.5)
        # Location statistics of the peculiar lenslets
        rows = np.asarray(lay['crow'])[bad]
        cols = np.asarray(lay['ccol'])[bad]
        # Position within the 64-lenslet block of the lenslet image
        inblk = np.asarray(lay['pos'])[bad] % 64
        print(f'{label}: {bad.sum()} peculiar lenslets; rows {rows.min()}-'
              f'{rows.max()}, cols {cols.min()}-{cols.max()}; position in '
              f'block min {inblk.min()} max {inblk.max()} (0/63 = block '
              f'edge); names {sorted(lay["name"][bad].tolist())}'
              if bad.sum() > 0 else f'{label}: none')
    fig.colorbar(im, ax=axes, shrink=0.85,
                 label='per-lenslet rms of the tilt residual (px)')
    fig.savefig(HERE / 'final_tilt_map.png', dpi=110, bbox_inches='tight')
    plt.close(fig)


def neighbour_deviation(res, k):
    """
    Deviation of a lenslet's Keck solution from its two block neighbours.

    The lenslets of a block are staggered by ~1.9 px per row, a nearly
    linear function of the row, so the mean wavelength of the rows above
    and below at the same pixel is a good prediction for the lenslet
    itself; a peculiar coefficient set stands out against it.

    Generated by JXP and Claude.

    Args:
        res (:obj:`dict`): Output of :func:`tilt_residuals`.
        k (:obj:`int`): Index of the lenslet in the layout.

    Returns:
        `numpy.ndarray`_: Deviation in pixels, PypeIt spectral order (NaN
        when a neighbour is missing or outside the band).
    """
    lay = res['layout']
    pos = np.asarray(lay['pos'])
    lam = res['lam'][:, ::-1]
    nb = [np.where(pos == pos[k] + o)[0] for o in (-1, 1)]
    if any(len(n) == 0 for n in nb) \
            or any(pos[n[0]] // 64 != pos[k] // 64 for n in nb):
        return np.full(lam.shape[1], np.nan)
    pred = 0.5 * (lam[nb[0][0]] + lam[nb[1][0]])
    disp = np.abs(np.gradient(lam[k]))
    dev = (lam[k] - pred) / disp
    return np.where(np.isfinite(res['resid'][k]), dev, np.nan)


def fig_lenslets(allres):
    """
    Residual curves of the worst Kn3 lenslets and the epoch comparison
    (``final_tilt_lenslets.png``).

    Generated by JXP and Claude.

    Args:
        allres (:obj:`dict`): :func:`tilt_residuals` output per case.
    """
    kn3, old = allres['Kn3 2024'], allres['Kn3 2016 coeffs']
    lay = kn3['layout']
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.6))
    order = np.argsort(np.nan_to_num(kn3['rms']))[::-1]
    colors = [ORANGE, BLUE, AQUA, PURPLE, INK2]
    pix = np.arange(kn3['resid'].shape[1])
    # (a) tilt residual and (b) neighbour deviation of the 5 worst lenslets
    for c, k in zip(colors, order[:5]):
        lab = f'{lay["name"][k]} (rms {kn3["rms"][k]:.2f})'
        axes[0].plot(pix, kn3['resid'][k], color=c, lw=1.0, label=lab)
        dev = neighbour_deviation(kn3, k)
        axes[1].plot(pix, dev, color=c, lw=1.0, label=lay['name'][k])
        g = np.isfinite(dev) & np.isfinite(kn3['resid'][k])
        if g.sum() > 10:
            r = np.corrcoef(dev[g], kn3['resid'][k][g])[0, 1]
            print(f'{lay["name"][k]}: tilt rms {kn3["rms"][k]:.2f} px, '
                  f'neighbour-deviation rms '
                  f'{np.sqrt(np.mean(dev[g]**2)):.2f} px, correlation with '
                  f'the tilt residual {r:.2f}; 2016-coefficient rms '
                  f'{old["rms"][k]:.2f} px')
    # A typical lenslet for reference
    k = order[len(order) // 2]
    axes[0].plot(pix, kn3['resid'][k], color='0.6', lw=0.8,
                 label=f'{lay["name"][k]} (median lenslet)')
    axes[0].set_xlabel('spectral pixel (lenslet image)')
    axes[0].set_ylabel('model - exact (px)')
    axes[0].set_title('Kn3 2024: tilt residual, worst lenslets', fontsize=9)
    axes[0].legend(fontsize=7, frameon=False)
    axes[1].axhline(0., color='0.6', lw=0.6)
    axes[1].set_xlabel('spectral pixel (lenslet image)')
    axes[1].set_ylabel('lenslet - mean of row neighbours (px)')
    axes[1].set_title('Keck solution vs its two block neighbours',
                      fontsize=9)
    axes[1].legend(fontsize=7, frameon=False)
    # (c) per-lenslet rms, 2016 vs 2024 coefficients (same layout)
    same = np.all(np.asarray(old['layout']['lens_id'])
                  == np.asarray(lay['lens_id']))
    if not same:
        raise PypeItError('Kn3 layouts differ between the two epochs.')
    bad, bad_old = peculiar(kn3), peculiar(old)
    ax = axes[2]
    ax.scatter(old['rms'], kn3['rms'], s=4, color=INK2, alpha=0.5)
    ax.scatter(old['rms'][bad], kn3['rms'][bad], s=14, color=ORANGE,
               label=f'peculiar in 2024 ({bad.sum()})')
    lim = [5e-3, 2.]
    ax.plot(lim, lim, color='0.6', lw=0.6)
    ax.axhline(PECULIAR, color=ORANGE, lw=0.6, ls=':')
    ax.axvline(PECULIAR, color=ORANGE, lw=0.6, ls=':')
    ax.set_xscale('log')
    ax.set_yscale('log')
    ax.set_xlim(lim)
    ax.set_ylim(lim)
    ax.set_xlabel('per-lenslet rms, 2016-epoch Kn3 coefficients (px)')
    ax.set_ylabel('per-lenslet rms, 2024-epoch Kn3 coefficients (px)')
    ax.set_title('Same lenslets, two coefficient epochs', fontsize=9)
    ax.legend(fontsize=7, frameon=False, loc='upper left')
    print(f'Kn3: peculiar in 2024 {bad.sum()}, in 2016 {bad_old.sum()}, '
          f'in both {np.sum(bad & bad_old)}; median rms ratio 2024/2016 '
          f'{np.nanmedian(kn3["rms"] / old["rms"]):.2f}')
    fig.tight_layout()
    fig.savefig(HERE / 'final_tilt_lenslets.png', dpi=110)
    plt.close(fig)


def redux_residuals(kn3_dir, res):
    """
    Spec1d minus spec2d wavelengths of every lenslet of the Kn3 reduction.

    The spec1d ``BOX_WAVE`` carries the exact per-lenslet Keck solution plus
    the OH zero point; the spec2d ``WAVEIMG`` is the block solution mapped
    through the tilts.  After removing the per-lenslet median (zero point),
    the remaining rms is the tilt residual of that lenslet.

    Generated by JXP and Claude.

    Args:
        kn3_dir (`Path`_): Kn3 reduction directory.
        res (:obj:`dict`): :func:`tilt_residuals` output of ``Kn3 2024``.

    Also returns the OH zero point of every lenslet, i.e. the median of
    the spec1d wavelengths (heliocentric correction divided out) minus the
    exact Keck solution, in pixels.

    Returns:
        :obj:`tuple`: Three arrays over the layout lenslets: the measured
        (reduction) and predicted (coefficient) rms after removing the
        per-lenslet median, and the OH zero point (px); NaN when the
        lenslet is absent.
    """
    sci = Path(kn3_dir) / 'Science'
    f1 = sorted(f for f in sci.glob('spec1d_*.fits') if '_ps' not in f.name)
    if len(f1) == 0:
        raise PypeItError(f'No spec1d file in {sci}.')
    f1 = f1[0]
    f2 = sci / f1.name.replace('spec1d_', 'spec2d_')
    log.info(f'Reading {f1.name} and {f2.name}')
    sobjs = SpecObjs.from_fitsfile(f1, chk_version=False)
    allspec2d = AllSpec2DObj.from_fits(f2, chk_version=False)
    waveimg = allspec2d[allspec2d.detectors[0]].waveimg
    lay = res['layout']
    index = {int(i): k for k, i in enumerate(lay['lens_id'])}
    meas = np.full(len(lay), np.nan)
    pred = np.full(len(lay), np.nan)
    zpt = np.full(len(lay), np.nan)
    # Exact Keck wavelengths (Angstrom) in PypeIt spectral order
    exact = res['lam'][:, ::-1] * 10.
    for s in sobjs:
        k = index.get(int(s.MASKDEF_ID))
        if k is None:
            continue
        col = int(np.round(s.SPAT_PIXPOS))
        w1, w2 = s.BOX_WAVE, waveimg[:, col]
        g = s.BOX_MASK & (w1 > 0) & (w2 > 0) & np.isfinite(res['resid'][k])
        if g.sum() < 50:
            continue
        disp = np.abs(np.gradient(w1))
        d = (w2 - w1)[g] / disp[g]
        meas[k] = np.sqrt(np.mean((d - np.median(d))**2))
        r = res['resid'][k][g]
        pred[k] = np.sqrt(np.mean((r - np.median(r))**2))
        # OH zero point: spec1d (heliocentric factor removed) - Keck exact
        w0 = w1 / s.VEL_CORR
        zpt[k] = np.median(((w0 - exact[k]) / disp)[g])
    return meas, pred, zpt


def neighbour_zeropoint(res, zpt):
    """
    OH zero point of each lenslet minus the mean of its two block neighbours,
    and the constant part of its Keck-solution deviation from them.

    If the Keck coefficients of a lenslet are offset by ``delta`` px from
    its true solution, the OH lines pull its zero point by ``-delta``
    relative to its neighbours; if the lenslet really is displaced, its
    zero point follows its neighbours (difference ~0).

    Generated by JXP and Claude.

    Args:
        res (:obj:`dict`): :func:`tilt_residuals` output of ``Kn3 2024``.
        zpt (`numpy.ndarray`_): OH zero point per lenslet (px).

    Returns:
        :obj:`tuple`: ``dev0`` (median Keck deviation from the neighbours)
        and ``dzpt`` (zero point minus the neighbours' mean), px.
    """
    pos = np.asarray(res['layout']['pos'])
    where = {int(p): k for k, p in enumerate(pos)}
    dev0 = np.full(len(pos), np.nan)
    dzpt = np.full(len(pos), np.nan)
    for k in range(len(pos)):
        nb = [where.get(int(pos[k]) + o) for o in (-1, 1)]
        if any(n is None or pos[n] // 64 != pos[k] // 64 for n in nb):
            continue
        dev = neighbour_deviation(res, k)
        if np.sum(np.isfinite(dev)) < 50:
            continue
        dev0[k] = np.nanmedian(dev)
        dzpt[k] = zpt[k] - 0.5 * (zpt[nb[0]] + zpt[nb[1]])
    return dev0, dzpt


def fig_redux(kn3_dir, allres):
    """
    Tilt residual measured in the Kn3 reduction (``final_tilt_redux.png``).

    Generated by JXP and Claude.

    Args:
        kn3_dir (`Path`_): Kn3 reduction directory.
        allres (:obj:`dict`): :func:`tilt_residuals` output per case.
    """
    kn3 = allres['Kn3 2024']
    meas, pred, zpt = redux_residuals(kn3_dir, kn3)
    dev0, dzpt = neighbour_zeropoint(kn3, zpt)
    bad = peculiar(kn3)
    g = np.isfinite(meas) & np.isfinite(pred)
    diff = np.abs(meas - pred)[g]
    print(f'Reduction: {g.sum()} lenslets; |measured - predicted| rms '
          f'median {np.median(diff):.4f} px, max {diff.max():.3f} px; '
          f'peculiar lenslets measured rms median '
          f'{np.nanmedian(meas[bad]):.2f} px, others '
          f'{np.nanmedian(meas[~bad]):.3f} px')
    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(11, 5))
    ax.scatter(pred[g & ~bad], meas[g & ~bad], s=4, color=INK2, alpha=0.5,
               label='other lenslets')
    ax.scatter(pred[g & bad], meas[g & bad], s=16, color=ORANGE,
               label=f'peculiar ({np.sum(g & bad)})')
    lim = [5e-3, 2.]
    ax.plot(lim, lim, color='0.6', lw=0.6)
    ax.set_xscale('log')
    ax.set_yscale('log')
    ax.set_xlim(lim)
    ax.set_ylim(lim)
    ax.set_xlabel('predicted from the Keck coefficients (px rms)')
    ax.set_ylabel('measured: spec2d WAVEIMG - spec1d BOX_WAVE (px rms)')
    ax.set_title('Kn3 reduction: spec2d vs spec1d wavelengths\n'
                 '(per-lenslet zero point removed)', fontsize=9)
    ax.legend(fontsize=8, frameon=False, loc='upper left')
    # (b) do the OH lines confirm the peculiar Keck solutions?
    h = np.isfinite(dev0) & np.isfinite(dzpt)
    ax2.scatter(dev0[h & ~bad], dzpt[h & ~bad], s=4, color=INK2, alpha=0.5,
                label='other lenslets')
    ax2.scatter(dev0[h & bad], dzpt[h & bad], s=16, color=ORANGE,
                label=f'peculiar ({np.sum(h & bad)})')
    lim = np.array([-1.6, 1.6])
    ax2.plot(lim, -lim, color=BLUE, lw=0.8, ls='--',
             label='coefficients wrong (OH pulls back)')
    ax2.plot(lim, 0 * lim, color=AQUA, lw=0.8, ls='--',
             label='coefficients right (lenslet displaced)')
    ax2.set_xlim(lim)
    ax2.set_ylim(lim)
    ax2.set_xlabel('Keck solution - mean of row neighbours, median (px)')
    ax2.set_ylabel('OH zero point - mean of row neighbours (px)')
    ax2.set_title('Kn3 reduction: OH zero points of the lenslets',
                  fontsize=9)
    ax2.legend(fontsize=7, frameon=False, loc='upper right')
    hb = h & bad
    if hb.sum() > 2:
        slope = np.polyfit(dev0[hb], dzpt[hb], 1)[0]
        print(f'OH zero-point test on {hb.sum()} peculiar lenslets: median '
              f'|Keck deviation| {np.median(np.abs(dev0[hb])):.2f} px, '
              f'median |zero-point difference| '
              f'{np.median(np.abs(dzpt[hb])):.2f} px, slope {slope:.2f} '
              f'(-1: coefficients wrong; 0: lenslet displaced); other '
              f'lenslets: std of the zero-point difference '
              f'{np.nanstd(dzpt[h & ~bad]):.3f} px')
        for k in np.where(hb)[0][np.argsort(-np.abs(dev0[hb]))][:8]:
            print(f'  {kn3["layout"]["name"][k]}: Keck deviation '
                  f'{dev0[k]:+.2f} px, zero-point difference '
                  f'{dzpt[k]:+.2f} px')
    fig.tight_layout()
    fig.savefig(HERE / 'final_tilt_redux.png', dpi=110)
    plt.close(fig)


