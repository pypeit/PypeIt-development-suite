def oh_metric(redux, lines, cache):
    """
    OH-line residual metric of every NGC 3245 A-B frame of a reduction.

    The metric of Report 06 (section 5.3): for every isolated OH line, the
    continuum-subtracted residual integrated over +-3 pixels and summed over
    the lenslets, divided by the sky-line flux of the B frame; median of the
    absolute values over the lines.  Computed on the spec2d without
    (``SCIIMG``) and with (``SCIIMG - SKYMODEL``) the Davies model.

    Generated by JXP and Claude.

    Args:
        redux (`Path`_): Reduction directory.
        lines (`numpy.ndarray`_): Isolated OH lines (Angstrom).
        cache (:obj:`dict`): Rectified B frames, by raw file name (filled).

    Returns:
        :obj:`dict`: (A-B metric, A-B-Davies metric, exposure time) by raw
        file name.
    """
    out = {}
    for f in sorted((Path(redux) / 'Science').glob('spec2d_*NGC3245*.fits')):
        with fits.open(f) as hdu:
            hdr = hdu[0].header
            sci = hdu['DET01-SCIIMG'].data
            model = hdu['DET01-SKYMODEL'].data
            wimg = hdu['DET01-WAVEIMG'].data
            bpm = hdu['DET01-BPMMASK'].data
        braw = mf.pair_sky(redux, hdr['FILENAME'])
        if braw not in cache:
            cache[braw] = vt.rectified_frame('Kbb_050', braw)
        bfr = cache[braw]
        pos = np.asarray(bfr['layout']['pos'])
        w = wimg[:, pos]
        # The M4 mask without the cosmic-ray bit, so that the M4 and M5
        # reductions are measured on the same pixels
        g = (bpm[:, pos] == 0) & bfr['gpm'][:, pos] & (w > 0)
        sk = bfr['image'][:, pos]
        r0 = mf.line_residuals(w, sci[:, pos], sk, g, lines)
        r1 = mf.line_residuals(w, sci[:, pos] - model[:, pos], sk, g, lines)
        # Same metric with the per-lenslet, OH-refined wavelengths of the
        # spec1d file (the spec2d WAVEIMG is the block solution through the
        # tilts, without the per-lenslet refinement of +0.54 px)
        s1d = next(f.parent.glob(f.name.replace('spec2d_', 'spec1d_')))
        wr = np.zeros_like(w)
        idx = {int(lid): k for k, lid in enumerate(bfr['layout']['lens_id'])}
        for so in SpecObjs.from_fitsfile(s1d, chk_version=False):
            ww = np.asarray(so.BOX_WAVE, dtype=float)
            vc = getattr(so, 'VEL_CORR', None)
            wr[:, idx[int(so.MASKDEF_ID)]] = ww / vc if vc else ww
        gr = g & (wr > 0)
        q0 = mf.line_residuals(wr, sci[:, pos], sk, gr, lines)
        q1 = mf.line_residuals(wr, sci[:, pos] - model[:, pos], sk, gr,
                               lines)
        out[hdr['FILENAME']] = (float(np.nanmedian(np.abs(r0))),
                                float(np.nanmedian(np.abs(r1))),
                                float(hdr['EXPTIME']),
                                float(np.nanmedian(np.abs(q0))),
                                float(np.nanmedian(np.abs(q1))))
    return out


def fig_ohscale(m5, m4):
    """
    Davies guard: per-frame OH metric for plain A-B and the M4/M5 scaling.

    Generated by JXP and Claude.

    Args:
        m5 (`Path`_): M5 Kbb reduction.
        m4 (`Path`_): M4 Kbb reduction.
    """
    ll = waveio.load_line_lists(['OH_OSIRIS'])[1]
    lw = wvutils.isolated_lines(ll['wave'], 15.,
                                line_ok=np.asarray(ll['NIST']) > 0)
    cache = {}
    r5 = oh_metric(m5, lw, cache)
    r4 = oh_metric(m4, lw, cache)
    names = sorted(set(r5) & set(r4))
    print('M4 definition (spec2d WAVEIMG) | refined per-lenslet wavelengths')
    print('frame                 exptime  A-B(M4)  Davies(M4)  A-B(M5)  '
          'Davies(M5)  M5 vs A-B | A-B   Dav(M4) Dav(M5)')
    rows = []
    for n in names:
        a4, d4, t, qa4, qd4 = r4[n]
        a5, d5, _, qa5, qd5 = r5[n]
        flag = 'better' if d5 < a5 - 1e-4 else ('equal' if abs(d5 - a5)
                                                 <= 1e-4 else 'WORSE')
        flag2 = 'better' if qd5 < qa5 - 1e-4 else ('equal' if abs(
            qd5 - qa5) <= 1e-4 else 'WORSE')
        rows.append((n, t, a4, d4, a5, d5))
        print(f'{n[3:20]:20s} {t:7.1f}  {a4:7.4f}  {d4:10.4f}  {a5:7.4f}  '
              f'{d5:10.4f}  {flag:6s} | {qa5:.4f} {qd4:.4f} {qd5:.4f} '
              f'{flag2}')
    long_ = [r for r in rows if r[1] > 100]
    print(f'600-s frames: median A-B {np.median([r[4] for r in long_]):.4f}'
          f' -> Davies M4 {np.median([r[3] for r in long_]):.4f}, M5 '
          f'{np.median([r[5] for r in long_]):.4f}; M5 improves '
          f'{sum(r[5] < r[4] - 1e-4 for r in long_)}/{len(long_)}, worse '
          f'{sum(r[5] > r[4] + 1e-4 for r in long_)}')

    fig, ax = plt.subplots(figsize=(9, 4))
    x = np.arange(len(rows))
    ax.plot(x, [r[4] for r in rows], 'o-', color=INK2, label='A - B')
    ax.plot(x, [r[3] for r in rows], 's--', color=ORANGE,
            label='A - B - Davies (M4 guard)')
    ax.plot(x, [r[5] for r in rows], 'o-', color=BLUE,
            label='A - B - Davies (M5 integrated guard)')
    ax.set_xticks(x)
    ax.set_xticklabels([f'{r[0][12:20]}\n{r[1]:.0f}s' for r in rows],
                       fontsize=6)
    ax.set_ylabel('median |OH-line residual| / sky line flux')
    ax.set_title('NGC 3245 A-B frames: OH residual metric (Report 06, 5.3)',
                 fontsize=9)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(HERE / 'm5_oh_guard.png', dpi=100)
    plt.close(fig)


def lenslet_waves(f):
    """
    Lenslet wavelengths of a spec1d file, heliocentric correction undone.

    Generated by JXP and Claude.

    Args:
        f (`Path`_): spec1d file.

    Returns:
        :obj:`dict`: Wavelength arrays by lenslet id (``MASKDEF_ID``).
    """
    out = {}
    for s in SpecObjs.from_fitsfile(f, chk_version=False):
        w = np.asarray(s.BOX_WAVE, dtype=float)
        vc = getattr(s, 'VEL_CORR', None)
        if vc is not None and np.isfinite(vc) and vc > 0:
            w = w / vc
        out[int(s.MASKDEF_ID)] = w
    return out


def std_offsets(redux):
    """
    Per-lenslet offsets (pixels) of the HD89239 standards from the 600-s
    NGC 3245 frames.

    Generated by JXP and Claude.

    Args:
        redux (`Path`_): Kbb reduction.

    Returns:
        :obj:`dict`: For every standard frame, the array of per-lenslet
        offsets from the median of the 600-s science solutions, and the
        list of per-science-frame median offsets.
    """
    sci = [f for f in sorted((Path(redux) / 'Science').glob(
        'spec1d_*NGC3245*.fits')) if fits.getheader(f)['EXPTIME'] > 100]
    W = [lenslet_waves(f) for f in sci]
    ids = sorted(set.intersection(*[set(w) for w in W]))
    ref = {i: np.median([w[i] for w in W], axis=0) for i in ids}

    def pixdiff(wa, wb):
        g = (wa > 0) & (wb > 0)
        if g.sum() < 100:
            return np.nan
        return float(np.median(((wa - wb) / np.abs(np.gradient(wb)))[g]))

    out = {}
    for fs in sorted((Path(redux) / 'Science').glob(
            'spec1d_*HD89239*.fits')):
        ws = lenslet_waves(fs)
        d = np.array([pixdiff(ws[i], ref[i]) for i in ids if i in ws])
        per = [np.nanmedian([pixdiff(ws[i], w[i]) for i in ids if i in ws])
               for w in W]
        out[fs.name[7:27]] = (d, per)
    return out


def fig_stdshift(m5, m4):
    """
    Short standards: wavelength offsets from the refined science frames.

    Generated by JXP and Claude.

    Args:
        m5 (`Path`_): M5 Kbb reduction.
        m4 (`Path`_): M4 Kbb reduction.
    """
    o5, o4 = std_offsets(m5), std_offsets(m4)
    fig, ax = plt.subplots(figsize=(7, 4))
    for lab, o, col in [('M4 (Keck solution)', o4, ORANGE),
                        ('M5 (arc-frame OH shifts)', o5, BLUE)]:
        for k, (name, (d, per)) in enumerate(o.items()):
            print(f'{lab:26s} {name}: median offset {np.nanmedian(d):+.3f} '
                  f'px, per-lenslet std {np.nanstd(d):.3f} px, |d| p95 '
                  f'{np.nanpercentile(np.abs(d), 95):.3f} px; vs each 600-s '
                  f'frame {min(per):+.3f} .. {max(per):+.3f} px')
            ax.hist(d, bins=np.linspace(-0.3, 0.8, 111), histtype='step',
                    color=col, label=lab if k == 0 else None)
    ax.axvline(0, color=INK2, lw=0.8)
    ax.set_xlabel('HD89239 (1.5 s) - NGC 3245 (600 s, refined) wavelength '
                  '[pixels]')
    ax.set_ylabel('lenslets')
    ax.legend(fontsize=8)
    ax.set_title('Per-lenslet offsets of the 4 HD89239 frames', fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / 'm5_std_shift.png', dpi=100)
    plt.close(fig)


def onside(flux, grid, lc, width, off):
    """
    On-band minus side-band line map (counts x Angstrom).

    Generated by JXP and Claude.

    Args:
        flux (`numpy.ndarray`_): Lenslet spectra (nlens, nwave).
        grid (`numpy.ndarray`_): Wavelength grid.
        lc (:obj:`float`): Window centre.
        width (:obj:`float`): Half width of the on band.
        off (:obj:`tuple`): Inner and outer offsets of the side bands.

    Returns:
        `numpy.ndarray`_: Line flux of every lenslet.
    """
    on = (grid > lc - width) & (grid < lc + width)
    side = ((grid > lc - off[1]) & (grid < lc - off[0])) \
        | ((grid > lc + off[0]) & (grid < lc + off[1]))
    c = np.nanmedian(flux[:, side], axis=1)
    return np.nansum(flux[:, on] - c[:, None], axis=1) * np.median(
        np.diff(grid))


def fig_linemap(m4):
    """
    Line-map step: fixed versus wide windows, H2 kinematics, sky-sky test,
    and the raw detector columns of the line per block.

    Generated by JXP and Claude.

    Args:
        m4 (`Path`_): Kbb reduction (the M4 one: the step was found there).
    """
    files = [f for f in sorted((Path(m4) / 'Science').glob(
        'spec1d_*NGC3245*.fits')) if fits.getheader(f)['EXPTIME'] > 100]
    grid = np.arange(19650., 23800., 2.5)
    ids, flux, _ = mf.stack_lenslets(files, grid)
    crow, ccol = np.divmod(ids, 51)
    lc = H2_S1 * (1 + Z_NGC3245)
    narrow = onside(flux, grid, lc, 8., (25., 45.))
    wide = onside(flux, grid, lc, 25., (40., 70.))

    def to_img(v):
        img = np.full((66, 51), np.nan)
        img[65 - crow, ccol] = v
        return img[:, 16:35]

    # H2 velocity per lenslet row (blocks 18-27), Gaussian + linear
    def gauss(x, a, mu, s, b, m):
        return a * np.exp(-0.5 * ((x - mu) / s)**2) + b + m * (x - lc)

    win = (grid > lc - 60) & (grid < lc + 60)
    sideb = ((grid > lc - 90) & (grid < lc - 60)) \
        | ((grid > lc + 60) & (grid < lc + 90))
    vel = []
    for r in range(20, 46):
        sel = (crow == r) & (ccol >= 18) & (ccol <= 27)
        if sel.sum() < 3:
            continue
        sp = np.nanmean(flux[sel] / np.nanmedian(flux[sel][:, sideb],
                                                 axis=1)[:, None], axis=0)
        try:
            p, cov = curve_fit(gauss, grid[win], sp[win],
                               p0=[0.03, lc, 6., 1., 0.])
        except RuntimeError:
            continue
        ev = np.sqrt(cov[1, 1]) / lc * C_KMS
        if p[0] > 0 and 2. < abs(p[2]) < 20. and ev < 40.:
            vel.append((65 - r, (p[1] / lc - 1) * C_KMS, ev))
    vel = np.array(vel)
    print('H2 1-0 S(1) velocity (km/s, relative to z = 0.004362) per '
          'flipped lenslet row:')
    print('  ' + ', '.join([f'{int(r)}: {v:+.0f}' for r, v, _ in vel]))
    sel = (ccol >= 18) & (ccol <= 27)
    for lab, m in [('fixed +-8 A window', narrow), ('wide +-25 A', wide)]:
        prof = np.array([np.nanmedian(m[sel & (crow == r)])
                         for r in range(24, 34)])
        print(f'  {lab}: crow 24-28 {np.mean(prof[:5]):.0f}, crow 29-33 '
              f'{np.mean(prof[5:]):.0f} counts x A (ratio '
              f'{np.mean(prof[5:]) / np.mean(prof[:5]):.2f})')

    # Sky-sky A-B pair (no source) at the H2 wavelength
    s1 = vt.rectified_frame('Kbb_050', 'OS.20240203.43383.79.fits')
    s2 = vt.rectified_frame('Kbb_050', 'OS.20240203.45436.78.fits')
    lay = s1['layout']
    pos = np.asarray(lay['pos'])
    row = np.asarray(lay['row'])
    col = np.asarray(lay['col'])
    d = s1['image'][:, pos] - s2['image'][:, pos]
    g = s1['gpm'][:, pos] & s2['gpm'][:, pos]
    lam = s1['lam']
    ss = np.full(pos.size, np.nan)
    for k in range(pos.size):
        l_ = lam[k]
        on = (np.abs(l_ - lc) < 8) & g[:, k]
        side = (np.abs(l_ - lc) > 25) & (np.abs(l_ - lc) < 45) & g[:, k]
        if on.sum() > 3 and side.sum() > 8:
            ss[k] = np.sum(d[on, k] - np.median(d[side, k])) \
                * np.median(np.abs(np.diff(l_)))
    sb = (col >= 2) & (col <= 11)
    sprof = np.array([np.nanmedian(ss[sb & (row == r)]) for r in range(64)])
    print(f'  sky-sky pair at H2: rows 22-27 {np.nanmean(sprof[22:28]):.0f}, '
          f'rows 28-33 {np.nanmean(sprof[28:34]):.0f}, row-to-row scatter '
          f'{np.nanstd(np.diff(sprof)) / np.sqrt(2):.0f} counts x A')

    fig = plt.figure(figsize=(13, 5))
    gs = fig.add_gridspec(1, 4, width_ratios=[1, 1, 1.4, 1.4])
    ext = [15.5, 34.5, -0.5, 65.5]
    for i, (m, t) in enumerate([(narrow, 'H2 S(1), +-8 A window'),
                                (wide, 'H2 S(1), +-25 A window')]):
        ax = fig.add_subplot(gs[0, i])
        img = to_img(m)
        v = np.nanpercentile(img, [2, 99.5])
        ax.imshow(img, origin='lower', cmap='magma', vmin=v[0], vmax=v[1],
                  extent=ext, aspect='equal')
        ax.axhline(36.5, color=AQUA, lw=0.8, ls=':')
        ax.set_title(t, fontsize=9)
        ax.set_xlabel('lenslet column')
        if i == 0:
            ax.set_ylabel('lenslet row (flipped)')
    ax = fig.add_subplot(gs[0, 2])
    ax.errorbar(vel[:, 0], vel[:, 1], yerr=vel[:, 2], fmt='o', ms=3,
                color=BLUE)
    for y in (-113, 113):
        ax.axhline(y, color=ORANGE, lw=0.8, ls='--')
    ax.axvline(36.5, color=AQUA, lw=0.8, ls=':')
    ax.set_xlabel('lenslet row (flipped)')
    ax.set_ylabel('H2 velocity (km/s)')
    ax.set_title('H2 kinematics; dashed: +-8 A window', fontsize=9)
    ax = fig.add_subplot(gs[0, 3])
    ax.plot(65 - (np.arange(64) + 1), sprof, 'o-', ms=3, color=INK2)
    ax.axvline(36.5, color=AQUA, lw=0.8, ls=':')
    ax.axhline(0, color=INK2, lw=0.5)
    ax.set_xlabel('lenslet row (flipped)')
    ax.set_ylabel('on - side at H2 (counts x A)')
    ax.set_title('Sky - sky pair (no source): no step', fontsize=9)
    fig.tight_layout()
    fig.savefig(HERE / 'm5_linemap.png', dpi=100)
    plt.close(fig)


def fig_crs(m5, m4, frame='OS.20240203.44064.64'):
    """
    Residual cosmic rays of one A-B frame: M4 (raw-frame L.A.Cosmic only)
    versus M5 (plus the second pass on the A-B spectra).

    Generated by JXP and Claude.

    Args:
        m5 (`Path`_): M5 Kbb reduction.
        m4 (`Path`_): M4 Kbb reduction.
        frame (:obj:`str`): Frame identifier.
    """
    res = {}
    for lab, rdx in [('M4', m4), ('M5', m5)]:
        f = next((Path(rdx) / 'Science').glob(f'spec2d_{frame}*.fits'))
        with fits.open(f) as hdu:
            r = hdu['DET01-SCIIMG'].data - hdu['DET01-SKYMODEL'].data
            ivar = hdu['DET01-IVARRAW'].data
            bpm = hdu['DET01-BPMMASK'].data
            w = hdu['DET01-WAVEIMG'].data
        nspat = r.shape[1]
        k = np.arange(nspat)
        nb = np.full((nspat, 4), -1)
        for i, d in enumerate((-2, -1, 1, 2)):
            j = k + d
            ok = (j >= 0) & (j < nspat)
            ok[ok] &= (j[ok] // 64) == (k[ok] // 64)
            nb[ok, i] = j[ok]
        out = {}
        for nsig in (5., 8.):
            cr = skysub.fiber_cosmic_rays(r, ivar, bpm == 0, w, nb,
                                          nsig=nsig)
            lab_, n = ndimage.label(cr, structure=np.array(
                [[0, 1, 0], [0, 1, 0], [0, 1, 0]]))
            out[nsig] = (int(cr.sum()), n, int((cr.sum(0) > 0).sum()))
        # CR bit of the M5 mask (bit value from the image bitmask)
        res[lab] = (out, r, bpm)
        print(f'{lab} {frame}: spikes (8 sigma) {out[8.][1]} events in '
              f'{out[8.][2]} lenslets; (5 sigma) {out[5.][1]} events in '
              f'{out[5.][2]} lenslets; masked pixels {int((bpm > 0).sum())}')
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.5))
    for ax, lab in zip(axes, ['M4', 'M5']):
        r = np.where(res[lab][2] == 0, res[lab][1], np.nan)
        sl = r[900:1100, 300:500]
        ax.imshow(sl, origin='lower', cmap='gray', aspect='auto',
                  vmin=np.nanpercentile(sl, 1), vmax=np.nanpercentile(sl, 99))
        ax.set_title(f'{lab}: A-B - sky model, {frame} (masked = white)',
                     fontsize=8)
        ax.set_xlabel('lenslet (spatial pixel 300-500)')
        ax.set_ylabel('spectral pixel 900-1100')
    fig.tight_layout()
    fig.savefig(HERE / 'm5_crs.png', dpi=100)
    plt.close(fig)


def fig_kn3(kn3):
    """
    Kn3/0.035" reduction of the nova V1405 Cas: continuum images of the two
    A-B frames and the point-source spectrum.

    Generated by JXP and Claude.

    Args:
        kn3 (`Path`_): Kn3 reduction directory.
    """
    files = sorted((Path(kn3) / 'Science').glob('spec1d_*v1405cas*.fits'))
    files = [f for f in files if '_ps' not in f.name]
    fig, axes = plt.subplots(1, len(files) + 1, figsize=(4 * len(files) + 5,
                                                         4.5))
    for ax, f in zip(axes, files):
        sobjs = SpecObjs.from_fitsfile(f, chk_version=False)
        ids = np.array([s.MASKDEF_ID for s in sobjs])
        ngood = np.array([np.sum(s.BOX_MASK) for s in sobjs])
        cont = np.array([np.median(s.BOX_COUNTS[s.BOX_MASK])
                         if ngood[k] > 50 else np.nan
                         for k, s in enumerate(sobjs)])
        crow, ccol = np.divmod(ids, 51)
        img = np.full((66, 51), np.nan)
        img[65 - crow, ccol] = cont
        k0 = np.nanargmax(cont)
        print(f'{f.name[7:27]}: {len(sobjs)} lenslet spectra, good pixels '
              f'per lenslet median {np.median(ngood):.0f} (min '
              f'{ngood.min()}); continuum peak at lenslet row {crow[k0]}, '
              f'col {ccol[k0]}')
