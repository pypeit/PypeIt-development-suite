def load_wc(base, det):
    """Return WaveCalib and SlitTraceSet for a run directory and det."""
    wc = WaveCalib.from_file(base / f'Calibrations/WaveCalib_A_0_{det}.fits',
                             chk_version=False)
    sl = SlitTraceSet.from_file(base / f'Calibrations/Slits_A_0_{det}.fits.gz',
                                chk_version=False)
    return wc, sl


def ok_fit(w):
    return w is not None and w.pypeitfit is not None


