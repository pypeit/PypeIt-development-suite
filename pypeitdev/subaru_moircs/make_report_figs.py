# F5: wavelength accuracy
#  (a) fit residuals of all lines used, in Angstrom, vs wavelength
#  (b) independent check: centroids of isolated OH lines measured directly
#      in each slit's sky spectrum vs the line-list wavelength
ll = np.loadtxt(LINELIST, skiprows=1, usecols=(1, 5), delimiter='|')
llw, lla = ll[:, 0], ll[:, 1]
# Isolated strong lines: no line with >25% of its amplitude within 80 A
# (~2 FWHM at R~500)
iso = []
for k in np.where((llw > 13500) & (llw < 22800))[0]:
    near = (np.abs(llw - llw[k]) < 80.) & (np.arange(llw.size) != k)
    if lla[k] > np.percentile(lla, 60) and not np.any(lla[near]
                                                       > 0.25 * lla[k]):
        iso.append(llw[k])
iso = np.array(iso)

res_w, res_d = [], []
chk_w, chk_d, chk_det = [], [], []
for det in DETS:
    wc, sl = load_wc(RUN, det)
    for j, wv in enumerate(wc.wv_fits):
        if not ok_fit(wv):
            continue
        npix = wv.spec.size
        # (a) fit residuals
        model = wv.pypeitfit.eval(wv.pixel_fit / (npix - 1))
        res_w.append(wv.wave_fit)
        res_d.append(wv.wave_fit - model)
        # (b) Gaussian-weighted centroid of each isolated line
        pix = np.arange(npix)
        cont = ndimage.median_filter(wv.spec, 61)
        flux = wv.spec - cont
        for lam in iso:
            if lam < wv.wave_soln.min() or lam > wv.wave_soln.max():
                continue
            p0 = np.interp(lam, wv.wave_soln, pix)
            win = (pix > p0 - 6) & (pix < p0 + 6)
            if win.sum() < 8:
                continue
            # Require a clear peak inside the window (robust noise)
            noise = stats.median_abs_deviation(
                flux[(pix > p0 - 60) & (pix < p0 + 60)], scale='normal')
            if flux[win].max() < 3 * noise:
                continue
            pc = p0
            for _ in range(5):
                wgt = np.exp(-0.5 * ((pix - pc) / 2.5) ** 2) * win \
                    * np.clip(flux, 0, None)
                if wgt.sum() <= 0:
                    break
                pc = np.sum(wgt * pix) / wgt.sum()
            if abs(pc - p0) > 3:
                continue
            chk_w.append(lam)
            chk_d.append(np.interp(pc, pix, wv.wave_soln) - lam)
            chk_det.append(det)
res_w, res_d = np.concatenate(res_w), np.concatenate(res_d)
chk_w, chk_d = np.array(chk_w), np.array(chk_d)
chk_det = np.array(chk_det)
disp = 7.6  # A/pix
# Split the residuals into a per-line offset shared by all slits (blends of
# OH lines at R~500 shift the effective line centre) and the slit-to-slit
# scatter about it (the relative precision between slits)
keys = np.round(res_w, 1)
uniq, inv, cnt = np.unique(keys, return_inverse=True, return_counts=True)
line_off = np.array([np.median(res_d[inv == u]) for u in range(uniq.size)])
use = cnt[inv] >= 5
demeaned = (res_d - line_off[inv])[use]
fig, ax = plt.subplots(1, 2, figsize=(13, 4.5), sharey=True)
ax[0].plot(res_w, res_d, '.', color=BLUE, ms=3, alpha=0.6)
ax[0].axhline(0, color=MUTED, lw=1)
ax[0].set_title(f'(a) Fit residuals, all 32 slits: {res_d.size} lines, '
                f'robust std '
                f'{stats.median_abs_deviation(res_d, scale="normal"):.1f} A',
                fontsize=10)
ax[0].set_xlabel('wavelength (A, vacuum)')
ax[0].set_ylabel('measured - fit (A)')
good_lines = cnt >= 5
ax[1].plot(uniq[good_lines], line_off[good_lines], 'o', color=ORANGE,
           ms=5, mec=SURF, mew=0.5, label='per-line offset (all slits)')
ax[1].plot(res_w[use], demeaned, '.', color=BLUE, ms=3, alpha=0.5,
           label='slit-to-slit scatter about it')
ax[1].axhline(0, color=MUTED, lw=1)
ax[1].set_title(f'(b) Per-line offsets: robust std '
                f'{stats.median_abs_deviation(line_off[good_lines], scale="normal"):.1f} A;'
                f' slit-to-slit: '
                f'{stats.median_abs_deviation(demeaned, scale="normal"):.1f} A',
                fontsize=10)
ax[1].set_xlabel('wavelength (A, vacuum)')
ax[1].legend(loc='lower right', fontsize=8)
ax[0].set_ylim(-25, 25)
for a in ax:
    sec = a.secondary_yaxis('right', functions=(lambda y: y / disp,
                                                 lambda p: p * disp))
    sec.set_ylabel('pixels')
fig.tight_layout()
fig.savefig(OUT / 'f5_wave_accuracy.png', dpi=80)
plt.close(fig)
summary['accuracy'] = dict(
    nfit=int(res_d.size),
    fit_robust_std_A=float(stats.median_abs_deviation(res_d,
                                                      scale='normal')),
    nlines_ge5=int(good_lines.sum()),
    line_offset_robust_std_A=float(stats.median_abs_deviation(
        line_off[good_lines], scale='normal')),
    slit_to_slit_robust_std_A=float(stats.median_abs_deviation(
        demeaned, scale='normal')),
    niso_lines=int(iso.size), nchk=int(chk_d.size),
    chk_median_A=float(np.median(chk_d)) if chk_d.size else None,
    chk_robust_std_A=float(stats.median_abs_deviation(
        chk_d, scale='normal')) if chk_d.size else None)

