for i, det in enumerate(DETS):
    s2 = spec2dobj.Spec2DObj.from_file(sci2d, det, chk_version=False)
    good = (s2.bpmmask.mask == 0) & (s2.ivarmodel > 0)
    chi = np.where(good, (s2.sciimg - s2.skymodel - s2.objmodel)
                   * np.sqrt(s2.ivarmodel), np.nan)
    a = fig.add_subplot(gs[:, i])
    a.imshow(chi, origin='lower', vmin=-4, vmax=4, cmap='gray',
             aspect='auto')
    a.grid(False)
    a.set_title(f'{det}: (A-B - sky - obj) / sigma', fontsize=10)
    a.set_xlabel('spatial pixel')
    c = chi[np.isfinite(chi)]
    summary['skysub'][det] = dict(
        chi_median=float(np.median(c)),
        chi_robust_std=float(stats.median_abs_deviation(c, scale='normal')),
        frac_gt5=float(np.mean(np.abs(c) > 5)))
    h = fig.add_subplot(gs[i, 2])
    bins = np.linspace(-6, 6, 121)
    h.hist(c, bins=bins, density=True, color=BLUE if i == 0 else ORANGE,
           histtype='stepfilled', alpha=0.8, label=det)
    h.plot(bins, stats.norm.pdf(bins), color=INK, lw=1.2, label='N(0,1)')
    h.set_yscale('log')
    h.set_ylim(1e-5, 1)
    h.set_title(f'{det}: robust std '
                f'{summary["skysub"][det]["chi_robust_std"]:.2f}, '
                f'|chi|>5: {100 * summary["skysub"][det]["frac_gt5"]:.2f}%',
                fontsize=9)
    h.legend(fontsize=8)
