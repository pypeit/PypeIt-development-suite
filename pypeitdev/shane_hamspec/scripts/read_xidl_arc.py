"""
Read the XIDL wavelength solution for the Shane/Hamspec ThAr arc.

Generated by JXP and Claude.

``Arc_01_fit.idl`` is the output of an XIDL (HIRES/ESI-style) reduction.  It
stores, per echelle order:

  - ``guess_ordr`` : the physical order numbers
  - ``sv_aspec``   : the extracted ThAr spectrum (norder x npix)
  - ``sv_lines``   : the identified arc lines (pix, wave) per order
  - ``all_arcfit`` : the per-order 1D wavelength fit (CHEBY/POLY of log10
                     air wavelength vs pixel), plus its RMS

PypeIt already ships a reader for exactly this format,
:func:`pypeit.core.wavecal.templates.xidl_esihires`, which evaluates the
per-order fits and converts air->vacuum.  This module wraps it and adds a
characterization summary used by the wavelength deep-dive report.

Inputs:
    path to the ``Arc_01_fit.idl`` save file.

Outputs (via :func:`load`):
    orders (ndarray), wave (norder x npix, vacuum AA), spec (norder x npix),
    and the per-order RMS array (from ``all_arcfit``, in the fit's units).
"""

from pathlib import Path

import numpy as np
from scipy.io import readsav

from pypeit.core.wavecal import templates


def load(xidl_file):
    """
    Load the XIDL arc solution and per-order RMS.

    Generated by JXP and Claude.

    Args:
        xidl_file (:obj:`str` or `pathlib.Path`):
            Path to ``Arc_01_fit.idl``.

    Returns:
        :obj:`tuple`: ``(orders, wave, spec, rms)`` where ``orders`` is the
        (N,) physical order vector, ``wave``/``spec`` are (N, npix) vacuum
        wavelength and flux arrays, and ``rms`` is the (N,) per-order fit RMS
        as stored by XIDL (only for the valid/returned orders).
    """
    xidl_file = str(xidl_file)
    orders, wave, spec = templates.xidl_esihires(xidl_file, log10=True)
    # Pull the per-order RMS from all_arcfit, matching the orders that
    # xidl_esihires kept (those with a CHEBY/POLY fit).
    raw = readsav(xidl_file)
    func = raw['all_arcfit']['FUNC']
    rms_all = raw['all_arcfit']['RMS']
    keep = np.array([f in (b'CHEBY', b'POLY') for f in func])
    # xidl_esihires returns order_vec[order_mask]; reconstruct the same mask
    rms = rms_all[keep]
    return orders, wave, spec, rms


def summary(xidl_file):
    """
    Print a human-readable summary of the XIDL solution.

    Generated by JXP and Claude.

    Args:
        xidl_file (:obj:`str` or `pathlib.Path`): ``Arc_01_fit.idl`` path.

    Returns:
        :obj:`tuple`: ``(orders, wave, spec, rms)`` from :func:`load`.
    """
    orders, wave, spec, rms = load(xidl_file)
    wmin = np.array([w[w > 0].min() if np.any(w > 0) else np.nan
                     for w in wave])
    wmax = np.array([w[w > 0].max() if np.any(w > 0) else np.nan
                     for w in wave])
    mid = wave[:, wave.shape[1] // 2]
    ml = orders * mid
    print(f'Valid orders        : {orders.size} '
          f'(physical order {orders.min()}-{orders.max()})')
    print(f'Wavelength range    : {np.nanmin(wmin):.1f} - '
          f'{np.nanmax(wmax):.1f} AA (vacuum)')
    print(f'm*lambda (center)   : median {np.nanmedian(ml[ml > 0]):.0f} AA, '
          f'std {np.nanstd(ml[ml > 0]):.0f}')
    # RMS is stored in the fit's units (log10 air AA); convert to mAA at a
    # representative 6000 AA via dlam = ln(10) * lam * dlog10 for readability.
    rms_maa = np.log(10) * 6000.0 * rms * 1e3
    print(f'Per-order fit RMS   : median {np.median(rms_maa):.1f} mAA, '
          f'max {np.max(rms_maa):.1f} mAA (@6000 AA; stored as log10 air AA)')
    print(f'Spectrum array      : {spec.shape} (norder x npix)')
    return orders, wave, spec, rms


if __name__ == '__main__':
    here = Path(__file__).resolve().parent.parent
    summary(here / 'Arc_01_fit.idl')
