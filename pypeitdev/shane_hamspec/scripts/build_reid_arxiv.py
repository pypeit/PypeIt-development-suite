"""
Build the PypeIt ``reid_arxiv`` composite arc for Shane/Hamspec from XIDL.

Generated by JXP and Claude.

Following the Keck/NIRES recipe (Q&A 20), the Shane/Hamspec wavelength
calibration uses ``method='reidentify'`` with a single template archive: one
extracted ThAr spectrum + wavelength solution per echelle order.  PypeIt reads
this as an `astropy.table.Table`_ with columns:

    wave  (norder x npix)  : vacuum wavelength solution per order
    flux  (norder x npix)  : extracted ThAr arc spectrum per order
    order (norder)         : physical echelle order number

(identical structure to ``keck_nires.fits``; see
:func:`pypeit.core.wavecal.waveio.load_reid_arxiv`).

The per-order ``(order, wave, flux)`` come straight from the XIDL solution via
:func:`pypeit.core.wavecal.templates.xidl_esihires` (Report 04 showed it is
compatible with the IRAF solution and uses the same physical order numbers).

Inputs:
    ``Arc_01_fit.idl`` (XIDL save).

Outputs:
    Writes ``shane_hamspec.fits`` into PypeIt's ``reid_arxiv`` data directory
    so the spectrograph can find it, and prints a summary.  Use ``--dry`` to
    write only a local copy under ``scripts/`` without touching the package.
"""

import sys
from pathlib import Path

import numpy as np
from astropy.table import Table

from pypeit import dataPaths
from pypeit.core.wavecal import templates


def build(xidl_file, outfile=None):
    """
    Build the Shane/Hamspec ``reid_arxiv`` FITS table from the XIDL solution.

    Generated by JXP and Claude.

    Args:
        xidl_file (:obj:`str` or `pathlib.Path`):
            Path to ``Arc_01_fit.idl``.
        outfile (:obj:`str` or `pathlib.Path`, optional):
            Output FITS path.  If None, writes ``shane_hamspec.fits`` into
            PypeIt's ``reid_arxiv`` data directory.

    Returns:
        :obj:`tuple`: ``(outfile, norder, npix)`` of the written archive.
    """
    orders, wave, spec = templates.xidl_esihires(str(xidl_file), log10=True)
    # Sort by order for tidiness (ascending physical order number)
    isort = np.argsort(orders)
    orders, wave, spec = orders[isort], wave[isort], spec[isort]

    tbl = Table()
    tbl['wave'] = wave.astype(float)     # vacuum AA, (norder, npix)
    tbl['flux'] = spec.astype(float)     # counts,     (norder, npix)
    tbl['order'] = orders.astype(int)    # physical order m

    if outfile is None:
        # Place alongside the other reid_arxiv templates so PypeIt finds it
        outfile = dataPaths.reid_arxiv.path / 'shane_hamspec.fits'
    outfile = Path(outfile)
    tbl.write(outfile, format='fits', overwrite=True)

    print(f'Wrote {outfile}')
    print(f'  norder = {len(orders)} (m = {orders.min()}-{orders.max()})')
    print(f'  npix   = {wave.shape[1]}')
    print(f'  wave   = {np.nanmin(wave[wave > 0]):.1f} - '
          f'{np.nanmax(wave):.1f} AA (vacuum)')
    return outfile, len(orders), wave.shape[1]


if __name__ == '__main__':
    here = Path(__file__).resolve().parent.parent
    xidl = here / 'Arc_01_fit.idl'
    if '--dry' in sys.argv:
        build(xidl, outfile=here / 'scripts' / 'shane_hamspec.fits')
    else:
        build(xidl)
