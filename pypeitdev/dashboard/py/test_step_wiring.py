"""
Manual / offscreen integration check for the PypeIt Dashboard status bar.

Generated by JXP and Claude.

This script exercises the full STEP-log wiring without running a real (slow)
reduction:

    pypeit.log.step(...)  ->  QtLogHandler.emit  ->  step_signal
                          ->  MainWindow.update_status_from_step  ->  labels

It builds the real ``MainWindow`` and ``QtLogHandler`` from
``pypeit.dashboard.dashboard``, feeds a synthetic STEP ``LogRecord`` through the
handler exactly as the live ``QueueListener`` would, and then asserts that the
six status-bar labels were updated.  Run it headless with::

    QT_QPA_PLATFORM=offscreen python test_step_wiring.py

It exits non-zero (and prints the mismatch) if any field is wrong, so it can
double as a smoke test.  Lingers in ``pypeitdev/dashboard`` until deleted.
"""

import logging
import sys

from qtpy.QtWidgets import QApplication

from pypeit import log
from pypeit.pkg import logger as pypeit_logger
from pypeit.dashboard.dashboard import MainWindow, QtLogHandler


def build_step_record(message):
    """
    Create a STEP-level ``LogRecord`` carrying ``message``.

    Generated by JXP and Claude.

    Inputs
    ------
    message : str
        The pipe-delimited payload to attach to the record.

    Returns
    -------
    logging.LogRecord
        A record whose ``levelname`` is ``"STEP"``.
    """
    # Mirror how the worker process produces the record (level 15 == STEP).
    return logging.LogRecord(
        name="pypeit", level=pypeit_logger.STEP, pathname=__file__,
        lineno=0, msg=message, args=(), exc_info=None,
    )


def main():
    """
    Run the offscreen wiring check and report pass/fail.

    Generated by JXP and Claude.

    Inputs
    ------
    None

    Returns
    -------
    int
        0 if every status field matched the injected STEP payload, else 1.
    """
    app = QApplication(sys.argv)  # required before any QWidget is built
    window = MainWindow()

    # Recreate the handler exactly as pypeit.dashboard.dashboard.main does.
    handler = QtLogHandler()
    handler.setFormatter(logging.Formatter(" %(levelname)s | %(message)s"))
    handler.log_signal.connect(window.update_logs)
    handler.step_signal.connect(window.update_status_from_step)

    # Feed a synthetic STEP record straight through the handler (this is what
    # the QueueListener does for each record pulled off the log queue).
    payload = "calib_id=7|det=2|calib_step=tilts|meta_step=Calibrations"
    handler.emit(build_step_record(payload))
    app.processEvents()  # let the queued signal/slot fire

    # Read back the labels and compare against the payload.
    status = window.dashboard_widget.meta_status_widget
    observed = {
        "calib_id": status.calibration_id.text(),
        "det": status.detector.text(),
        "calib_step": status.calibration_step.text(),
        "meta_step": status.meta_step.text(),
    }
    expected = {
        "calib_id": "7", "det": "2",
        "calib_step": "tilts", "meta_step": "Calibrations",
    }

    ok = observed == expected
    print("expected:", expected)
    print("observed:", observed)
    print("PASS" if ok else "FAIL")

    # Also confirm log.step() actually emits at the STEP level (defensive).
    print("log has step():", hasattr(log, "step"))

    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
