def draw_logo(ax):
    """
    Place the PypeIt logo in the top-right corner of the window.

    Generated by JXP and Claude.

    The logo lives in the empty band to the right of the tabs (above the header
    banner) so it never overlaps view content.  Uses the downscaled local copy
    (600x317 px); zoom ~0.19 makes it ~7 x-units wide.

    Parameters
    ----------
    ax : matplotlib.axes.Axes
        Axis to draw on (data coords 0..100).

    Returns
    -------
    None
    """
    logo = find_logo()
    if logo is not None:
        place_image(ax, logo, center=(92.0, 97.4), zoom=0.19)


def draw_scope_toolbar(ax, y0, include_filter=True):
    """
    Draw the scope toolbar: calib-group and detector drop-downs + controls.

    Generated by JXP and Claude.

    The drop-downs are the anti-clutter mechanism: they scope the detailed
    tables/buttons below to a single (calibration group, detector/mosaic).

    Parameters
    ----------
    ax : matplotlib.axes.Axes
        Axis to draw on.
    y0 : float
        Bottom edge (data coords) of the 3-unit-tall toolbar.
    include_filter : bool, optional
        If True, include a "Filter" control (used by the Status view).

    Returns
    -------
    None
    """
    yc = y0 + 1.5

    def dropdown(x, w, label):
        ax.add_patch(Rectangle((x, y0), w, 3.0, facecolor='white',
                               edgecolor='#607D8B'))
        ax.text(x + 0.8, yc, label, va='center', fontsize=9, color='#263238')
        ax.text(x + w - 1.2, yc, '▾', va='center', ha='center', fontsize=9,
                color='#607D8B')

    ax.text(4, yc, 'Scope:', va='center', fontsize=9.5, fontweight='bold',
            color='#37474F')
    dropdown(12, 22, 'Calib group:  0')
    dropdown(35, 22, 'Detector:  DET01')
    if include_filter:
        ax.add_patch(Rectangle((74, y0), 13, 3.0, facecolor='white',
                               edgecolor='#9E9E9E'))
        ax.text(80.5, yc, 'Filter ▾', ha='center', va='center', fontsize=9,
                color='#424242')
    ax.add_patch(Rectangle((88, y0), 9.5, 3.0, facecolor='#1565C0',
                           edgecolor='#1565C0'))
    ax.text(92.7, yc, '↻ Refresh', ha='center', va='center', fontsize=9,
            color='white')


def draw_color_key(ax, y):
    """
    Draw the Dashboard-wide status color key on a single row.

    Generated by JXP and Claude.

    Parameters
    ----------
    ax : matplotlib.axes.Axes
        Axis to draw on.
    y : float
        Vertical center (data coords) of the key row.

    Returns
    -------
    None
    """
    ax.text(4, y, 'Status key', fontsize=9, fontweight='bold',
            color='#37474F', va='center')
    order = ['success', 'running', 'fail', 'required_undone', 'not_required',
             'not_used']
    x = 16
    for key in order:
        fill, edge, glyph, label = PALETTE[key]
        ax.add_patch(FancyBboxPatch((x, y - 0.9), 1.8, 1.8,
                     boxstyle='round,pad=0.1,rounding_size=0.4',
                     facecolor=fill, edgecolor=edge, linewidth=1.0))
        ax.text(x + 0.9, y, glyph, ha='center', va='center', fontsize=9,
                color=status_text_color(key))
        ax.text(x + 2.4, y, label, va='center', fontsize=8.5, color='#546E7A')
        x += 13.5
